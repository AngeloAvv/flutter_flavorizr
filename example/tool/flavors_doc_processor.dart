// A custom processor of flavorizr: it writes FLAVORS.md, which lists the
// flavors of the app. It is pure Dart, with no `package:flutter` import, since
// `tool/flavorizr.dart` runs with `dart run`.

import 'dart:io';

import 'package:flutter_flavorizr/experimental.dart';
import 'package:flutter_flavorizr/flutter_flavorizr.dart';

/// Writes `FLAVORS.md`, a table of the flavors with their app name and the
/// identifiers of each platform.
///
/// The file is *managed*: flavorizr writes it whole, records its hash in
/// `flavorizr.lock`, and `flavorizr status` reports it when it was edited or
/// is out of date.
class FlavorsDocProcessor extends FlavorizrProcessor {
  /// The file the processor writes, relative to the project.
  static const path = 'FLAVORS.md';

  /// Creates the processor.
  const FlavorsDocProcessor();

  /// The id of a processor is namespaced. `acme` is the one of this project:
  /// the namespaces of flavorizr (`android`, `ios`, ...) are reserved.
  @override
  String get id => 'acme:flavorsDoc';

  /// What the processor reads or writes, so that flavorizr knows what to copy
  /// to the workspace of the run, diff and write back.
  @override
  Set<String> get paths => const {path};

  @override
  Future<void> apply(FlavorizrContext ctx) async {
    final rows = [
      for (final MapEntry(key: name, value: flavor)
          in ctx.config.flavors.entries)
        '| `$name` | ${flavor.app.name} | '
            '${flavor.android?.applicationId ?? '-'} | '
            '${flavor.ios?.bundleId ?? '-'} | '
            '${flavor.macos?.bundleId ?? '-'} |',
    ];

    // Everything is written below `ctx.root`, the workspace of the run, never
    // to the project itself.
    await File('${ctx.root.path}/$path').writeAsString(
      [
        '# Flavors',
        '',
        'Generated by `flavorizr`: do not edit.',
        '',
        '| Flavor | App | Android | iOS | macOS |',
        '| --- | --- | --- | --- | --- |',
        ...rows,
        '',
      ].join('\n'),
    );

    // Say what the processor owns: a managed file is written whole.
    ctx.track(const Artifact.managed(path));
  }
}
