/// Thrown when a recipe contains itself, directly or through other recipes.
class RecipeCycleException implements Exception {
  /// The recipe names along the cycle. Each recipe contains the next one, and
  /// the last name repeats the first, e.g. `[a, b, a]`.
  final List<String> cycle;

  RecipeCycleException(this.cycle);

  @override
  String toString() =>
      'The recipes contain each other in a cycle: ${cycle.join(' -> ')}.';
}
