import 'package:collection/collection.dart';
import 'package:flutter_flavorizr/src/engine/lock/flavorizr_lock.dart';
import 'package:flutter_flavorizr/src/engine/lock/lock_version.dart';
import 'package:flutter_flavorizr/src/engine/lock/lock_yaml.dart';
import 'package:flutter_flavorizr/src/engine/ownership.dart';
import 'package:flutter_flavorizr/src/exception/malformed_lock_file_exception.dart';
import 'package:flutter_flavorizr/src/exception/unsupported_lock_version_exception.dart';
import 'package:yaml/yaml.dart';

/// Converts a [FlavorizrLock] to and from the text of `flavorizr.lock`.
///
/// The text is deterministic: the same lock is always written to the same
/// bytes, whatever the order its maps were filled in.
abstract final class LockCodec {
  static const _header =
      '# flavorizr.lock: generated by flutter_flavorizr, do not edit.\n'
      '# Commit this file: it lets flavorizr remove what it generated.\n';

  /// Writes [lock] as deterministic YAML.
  static String encode(FlavorizrLock lock) =>
      _header +
      LockYaml.emit({
        'schemaVersion': FlavorizrLock.currentSchemaVersion,
        'flavorizrVersion': lock.flavorizrVersion,
        'flavors': lock.flavors,
        'processors': {
          for (final entry in lock.processors.entries)
            entry.key: _encodeProcessor(entry.value),
        },
      });

  static Map<String, Object?> _encodeProcessor(ProcessorLock processor) => {
    if (processor.files.isNotEmpty)
      'files': {
        for (final entry in processor.files.entries)
          entry.key: {
            'ownership': entry.value.ownership.name,
            'hash': ?entry.value.hash,
          },
      },
    if (processor.regions.isNotEmpty) 'regions': processor.regions,
    if (processor.keys.isNotEmpty) 'keys': processor.keys,
    if (processor.objects.isNotEmpty)
      'objects': {
        for (final entry in processor.objects.entries)
          entry.key: entry.value.toList()..sort(),
      },
    if (processor.inputs.isNotEmpty) 'inputs': processor.inputs,
  };

  /// Reads the text of `flavorizr.lock`.
  ///
  /// [runningVersion] is the version of the flavorizr that is reading. A lock
  /// written by a newer format or a newer flavorizr is refused with an
  /// [UnsupportedLockVersionException] before anything else is read from it,
  /// since its shape is not known. Older ones are read.
  ///
  /// Throws a [MalformedLockFileException] when [content] is not a lock.
  static FlavorizrLock decode(
    String content, {
    required String runningVersion,
  }) {
    final Object? parsed;

    try {
      parsed = loadYaml(content);
    } on YamlException catch (error) {
      throw MalformedLockFileException(error.message);
    }

    final root = _asMap(parsed, 'the lock');
    _guardVersion(root, runningVersion);

    try {
      return FlavorizrLock(
        flavorizrVersion: _asString(
          root['flavorizrVersion'],
          'flavorizrVersion',
        ),
        flavors: _decodeStrings('flavors', root['flavors']),
        processors: {
          for (final entry in _asMap(root['processors'], 'processors').entries)
            _asString(entry.key, 'a processor id'): _decodeProcessor(
              entry.key as String,
              entry.value,
            ),
        },
      );
    } on ArgumentError catch (error) {
      throw MalformedLockFileException('${error.message}');
    }
  }

  static void _guardVersion(YamlMap root, String runningVersion) {
    final schemaVersion = root['schemaVersion'];

    if (schemaVersion is! int || schemaVersion < 1) {
      throw const MalformedLockFileException(
        'schemaVersion must be a positive integer',
      );
    }

    final lockVersion = root['flavorizrVersion'];
    final writer = lockVersion is String ? lockVersion : null;

    if (schemaVersion > FlavorizrLock.currentSchemaVersion) {
      throw UnsupportedLockVersionException(
        lockVersion: writer,
        schemaVersion: schemaVersion,
        runningVersion: runningVersion,
      );
    }

    try {
      if (writer == null) {
        throw const FormatException('flavorizrVersion must be a string');
      }

      if (compareVersions(writer, runningVersion) > 0) {
        throw UnsupportedLockVersionException(
          lockVersion: writer,
          runningVersion: runningVersion,
        );
      }
    } on FormatException catch (error) {
      throw MalformedLockFileException(
        'flavorizrVersion is not a version (${error.message}: ${error.source})',
      );
    }
  }

  static ProcessorLock _decodeProcessor(String id, Object? node) {
    final processor = _asMap(node, 'processor $id');

    return ProcessorLock(
      files: {
        for (final entry in _asMap(
          processor['files'] ?? YamlMap(),
          '$id files',
        ).entries)
          _asString(entry.key, 'a file path of $id'): _decodeFile(
            '$id ${entry.key}',
            entry.value,
          ),
      },
      regions: _decodeNested(id, 'regions', processor['regions']),
      keys: _decodeNested(id, 'keys', processor['keys']),
      objects: {
        for (final entry in _asMap(
          processor['objects'] ?? YamlMap(),
          '$id objects',
        ).entries)
          _asString(entry.key, 'a file path of $id'): {
            for (final uuid in _asList(entry.value, '$id objects ${entry.key}'))
              _asString(uuid, '$id objects ${entry.key}'),
          },
      },
      inputs: _decodeStrings('$id inputs', processor['inputs']),
    );
  }

  static Map<String, Map<String, String>> _decodeNested(
    String id,
    String section,
    Object? node,
  ) => {
    for (final entry in _asMap(node ?? YamlMap(), '$id $section').entries)
      _asString(entry.key, 'a file path of $id'): _decodeStrings(
        '$id $section ${entry.key}',
        entry.value,
      ),
  };

  static Map<String, String> _decodeStrings(String where, Object? node) => {
    for (final entry in _asMap(node ?? YamlMap(), where).entries)
      _asString(entry.key, 'a key of $where'): _asString(
        entry.value,
        '$where ${entry.key}',
      ),
  };

  static LockedFile _decodeFile(String where, Object? node) {
    final file = _asMap(node, where);
    final name = _asString(file['ownership'], '$where ownership');
    final ownership = Ownership.values.firstWhereOrNull((o) => o.name == name);

    if (ownership == null) {
      throw MalformedLockFileException('$where has an unknown class `$name`');
    }

    return LockedFile(
      ownership: ownership,
      hash: file['hash'] == null
          ? null
          : _asString(file['hash'], '$where hash'),
    );
  }

  static YamlMap _asMap(Object? node, String where) {
    if (node is YamlMap) return node;

    throw MalformedLockFileException('$where must be a mapping');
  }

  static YamlList _asList(Object? node, String where) {
    if (node is YamlList) return node;

    throw MalformedLockFileException('$where must be a list');
  }

  static String _asString(Object? node, String where) {
    if (node is String) return node;

    throw MalformedLockFileException('$where must be a string');
  }
}
