import 'dart:io';

import 'package:flutter_flavorizr/src/engine/shadow/workspace_paths.dart';

/// The text every block flavorizr marks in a file of the project has.
const _marker = 'autogenerated by flutter_flavorizr';

/// The files that carry the marked blocks of 2.x (and of 3.x).
const _markedFiles = [
  'android/app/build.gradle',
  'android/app/build.gradle.kts',
  'linux/CMakeLists.txt',
  'linux/runner/CMakeLists.txt',
  'linux/runner/my_application.cc',
  'windows/runner/CMakeLists.txt',
];

/// The files flavorizr generates whole, and that no project has until it ran.
const _wholeFiles = [
  'android/app/flavorizr.gradle',
  'android/app/flavorizr.gradle.kts',
];

const _modes = ['Debug', 'Profile', 'Release'];

/// The files of the project at [projectRoot] that flavorizr made before there
/// was a `flavorizr.lock`: the ones 2.x made, or the ones of a project whose
/// lock was lost. Relative paths, sorted, without repeats.
///
/// Only what is **specific** to flavorizr is looked for, since a project that
/// has some of them is read as the baseline of the run, and what is not
/// flavorizr's would be taken for it: a project that was flavorized by hand
/// has schemes, build configurations named `Debug-<flavor>` and app icon sets
/// of its own, and its files are the user's, which a run asks about. What tells
/// the project was flavorized by flavorizr:
///
/// * the marked blocks of `build.gradle(.kts)`, of the CMake files of Linux and
///   Windows and of `my_application.cc`, and `flavorizr.gradle(.kts)`;
/// * for each of [flavors], which are the ones of the configuration, the
///   xcconfigs flavorizr names (`Flutter/<flavor>Debug.xcconfig` and the ones of
///   macOS) and the launch storyboard of iOS (`<flavor>LaunchScreen.storyboard`).
///
/// A project 2.x flavorized for a flavor the configuration dropped before the
/// first run of 3.x cannot be told by the name of the flavor: nothing says which
/// flavors it had. That is what `adopt --flavors` is for.
///
/// A link is never followed, and a flavor that is not the name of a single
/// folder is ignored.
List<String> findLegacyArtifacts(
  Directory projectRoot, {
  required Iterable<String> flavors,
}) {
  final found = <String>{};

  bool isFile(String path) =>
      !goesThroughLink(projectRoot, path) &&
      FileSystemEntity.typeSync(
            resolveIn(projectRoot, path),
            followLinks: false,
          ) ==
          FileSystemEntityType.file;

  String? read(String path) {
    if (!isFile(path)) return null;

    try {
      return File(resolveIn(projectRoot, path)).readAsStringSync();
    } on FileSystemException {
      return null;
    } on FormatException {
      return null;
    }
  }

  for (final path in _wholeFiles) {
    if (isFile(path)) found.add(path);
  }

  for (final path in _markedFiles) {
    if (read(path)?.contains(_marker) ?? false) found.add(path);
  }

  for (final flavor in flavors.where(_isFolderName).toSet()) {
    for (final platform in ['ios', 'macos']) {
      for (final mode in _modes) {
        for (final folder in ['Flutter', 'Runner/Configs']) {
          final xcconfig = '$platform/$folder/$flavor$mode.xcconfig';

          if (isFile(xcconfig)) found.add(xcconfig);
        }
      }
    }

    final storyboard = 'ios/Runner/${flavor}LaunchScreen.storyboard';

    if (isFile(storyboard)) found.add(storyboard);
  }

  return found.toList()..sort();
}

bool _isFolderName(String name) =>
    name.isNotEmpty &&
    name != '.' &&
    name != '..' &&
    !name.contains(RegExp(r'[/\\\x00]'));
