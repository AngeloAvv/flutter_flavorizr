import 'package:flutter_flavorizr/src/engine/processors/linux/marked_text.dart';
import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';

/// The edits flavorizr makes to `linux/runner/CMakeLists.txt`.
///
/// A freshly generated runner does not forward `FLUTTER_APP_FLAVOR` as a
/// preprocessor define, so `my_application.cc` could not read it with
/// `#ifdef FLUTTER_APP_FLAVOR`. The only part flavorizr owns is a *marked
/// region* right after the definition of `APPLICATION_ID` that does it:
///
/// ```cmake
/// # ----- BEGIN FLUTTER_APP_FLAVOR (autogenerated by flutter_flavorizr) -----
/// if(DEFINED FLUTTER_APP_FLAVOR AND NOT FLUTTER_APP_FLAVOR STREQUAL "")
///   add_definitions(-DFLUTTER_APP_FLAVOR="${FLUTTER_APP_FLAVOR}")
/// endif()
/// # ----- END FLUTTER_APP_FLAVOR (autogenerated by flutter_flavorizr) -----
/// ```
///
/// The markers are the ones 2.x writes. Everything outside the region is
/// written back byte for byte. See [MarkedText.upsert].
abstract final class LinuxRunnerCMakeListsEditor {
  /// The markers of the region.
  static const RegionMarker marker = RegionMarker(
    'FLUTTER_APP_FLAVOR',
    comment: '#',
  );

  static const String _applicationIdDefinitionAnchor =
      r'add_definitions(-DAPPLICATION_ID="${APPLICATION_ID}")';

  static const List<String> _body = [
    'if(DEFINED FLUTTER_APP_FLAVOR AND NOT FLUTTER_APP_FLAVOR STREQUAL "")',
    r'  add_definitions(-DFLUTTER_APP_FLAVOR="${FLUTTER_APP_FLAVOR}")',
    'endif()',
  ];

  /// Returns [source] with the region up to date.
  ///
  /// Throws a [MalformedResourceException] when [source], leaving the region
  /// out, does not define `APPLICATION_ID`, or when the markers do not form a
  /// region.
  static String withFlavorDefinition(String source) {
    final text = MarkedText(source, [marker]);

    if (!text.outside.any(
      (line) => line.text.contains(_applicationIdDefinitionAnchor),
    )) {
      throw MalformedResourceException(source);
    }

    return text.upsert(
      marker,
      _body,
      anchor: (lines) => lines
          .where((line) => line.text.contains(_applicationIdDefinitionAnchor))
          .firstOrNull,
    );
  }

  /// Returns the content of [source] flavorizr owns, which is the region. It is
  /// what the lock hashes. See [MarkedText.ownedContent].
  static String ownedContent(String source) =>
      MarkedText.ownedContent(source, [marker]);
}
