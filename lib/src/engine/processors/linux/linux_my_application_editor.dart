import 'package:flutter_flavorizr/src/engine/processors/linux/marked_text.dart';
import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';
import 'package:flutter_flavorizr/src/utils/desktop_utils.dart';

/// The edits flavorizr makes to `linux/runner/my_application.cc`.
///
/// The file belongs to the user, and every edit is inside a *marked region*:
/// nothing outside the markers is ever changed. There are two ways to set the
/// title of the window, and each one has its regions.
///
/// **The title is a variable** (templates that have flavor support, and the
/// files a 2.x run refactored): one region, right after the declaration, that
/// overrides it.
///
/// ```c
/// const gchar* window_title = "example";
/// // ----- BEGIN window_title (autogenerated by flutter_flavorizr) -----
/// #ifdef FLUTTER_APP_FLAVOR
/// if (g_strcmp0(FLUTTER_APP_FLAVOR, "apple") == 0) {
///   window_title = "Apple App";
/// }
/// #endif
/// // ----- END window_title (autogenerated by flutter_flavorizr) -----
/// ```
///
/// **The title is two string literals** (what `flutter create` writes): 2.x
/// declared a variable and rewrote the two calls to use it, which cannot be
/// tracked or reverted. Here the calls are left alone, and a region right after
/// each one sets the title again for the flavor, which is what takes effect:
///
/// ```c
/// gtk_header_bar_set_title(header_bar, "example");
/// // ----- BEGIN header_bar_title (autogenerated by flutter_flavorizr) -----
/// #ifdef FLUTTER_APP_FLAVOR
/// if (g_strcmp0(FLUTTER_APP_FLAVOR, "apple") == 0) {
///   gtk_header_bar_set_title(header_bar, "Apple App");
/// }
/// #endif
/// // ----- END header_bar_title (autogenerated by flutter_flavorizr) -----
/// ```
///
/// The markers of the first kind are the ones 2.x writes. A region of the other
/// kind is dropped, for example when a newer template declares the variable the
/// file did not have. A region that is already there is regenerated where it
/// is, so that a flavor that was dropped from the configuration is not in it
/// anymore. See [MarkedText.upsert].
abstract final class LinuxMyApplicationEditor {
  /// The region that overrides the title variable.
  static const RegionMarker variableMarker = RegionMarker(
    'window_title',
    comment: '//',
  );

  /// The region that sets the title of the header bar again.
  static const RegionMarker headerBarMarker = RegionMarker(
    'header_bar_title',
    comment: '//',
  );

  /// The region that sets the title of the plain window again.
  static const RegionMarker windowMarker = RegionMarker(
    'plain_window_title',
    comment: '//',
  );

  static const List<RegionMarker> _markers = [
    variableMarker,
    headerBarMarker,
    windowMarker,
  ];

  static final RegExp _windowTitleVariable = RegExp(
    r'^\s*const gchar\* window_title = "[^"]*";\s*$',
  );
  static final RegExp _headerBarTitleLiteral = RegExp(
    r'^\s*gtk_header_bar_set_title\(header_bar, "[^"]*"\);\s*$',
  );
  static final RegExp _windowTitleLiteral = RegExp(
    r'^\s*gtk_window_set_title\(window, "[^"]*"\);\s*$',
  );

  /// Returns [source] with the regions up to date for [titles], the title of
  /// the window of each flavor by name.
  ///
  /// Throws a [MalformedResourceException] when [source], leaving the regions
  /// out, neither declares `window_title` nor sets the title with a literal, or
  /// when the markers do not form regions.
  static String withWindowTitles(String source, Map<String, String> titles) {
    final outside = MarkedText(source, _markers).outside;

    if (outside.any((line) => _windowTitleVariable.hasMatch(line.text))) {
      return _upsert(
        _without(source, [headerBarMarker, windowMarker]),
        variableMarker,
        _body(titles, (title) => 'window_title = "$title";'),
        _windowTitleVariable,
      );
    }

    final hasHeaderBar = outside.any(
      (line) => _headerBarTitleLiteral.hasMatch(line.text),
    );
    final hasWindow = outside.any(
      (line) => _windowTitleLiteral.hasMatch(line.text),
    );

    if (!hasHeaderBar && !hasWindow) throw MalformedResourceException(source);

    var patched = _without(source, [variableMarker]);

    if (hasHeaderBar) {
      patched = _upsert(
        patched,
        headerBarMarker,
        _body(
          titles,
          (title) => 'gtk_header_bar_set_title(header_bar, "$title");',
        ),
        _headerBarTitleLiteral,
      );
    }

    if (hasWindow) {
      patched = _upsert(
        patched,
        windowMarker,
        _body(titles, (title) => 'gtk_window_set_title(window, "$title");'),
        _windowTitleLiteral,
      );
    }

    return patched;
  }

  /// Returns the content of [source] flavorizr owns, which is the regions. It is
  /// what the lock hashes. See [MarkedText.ownedContent].
  static String ownedContent(String source) =>
      MarkedText.ownedContent(source, _markers);

  static String _without(String source, List<RegionMarker> markers) =>
      markers.fold(
        source,
        (text, marker) => MarkedText(text, _markers).remove(marker),
      );

  static String _upsert(
    String source,
    RegionMarker marker,
    List<String> body,
    RegExp anchor,
  ) => MarkedText(source, _markers).upsert(
    marker,
    body,
    anchor: (lines) =>
        lines.where((line) => anchor.hasMatch(line.text)).firstOrNull,
  );

  static List<String> _body(
    Map<String, String> titles,
    String Function(String title) statement,
  ) {
    final entries = titles.entries.toList(growable: false);

    return [
      '#ifdef FLUTTER_APP_FLAVOR',
      for (final (index, entry) in entries.indexed) ...[
        '${index == 0 ? 'if' : '} else if'} (g_strcmp0(FLUTTER_APP_FLAVOR, "${entry.key}") == 0) {',
        '  ${statement(escapeQuotedString(entry.value))}',
      ],
      '}',
      '#endif',
    ];
  }
}
