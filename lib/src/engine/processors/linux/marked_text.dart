import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';

/// The pair of lines flavorizr writes around a part of a file it owns, such as
///
/// ```cmake
/// # ----- BEGIN APPLICATION_ID (autogenerated by flutter_flavorizr) -----
/// # ----- END APPLICATION_ID (autogenerated by flutter_flavorizr) -----
/// ```
///
/// The markers are the ones 2.x writes, so a project that was flavorized by a
/// 2.x run is recognized and nothing is duplicated. A marker is a whole line,
/// whatever its indentation and line ending.
final class RegionMarker {
  /// What the region is about, e.g. `APPLICATION_ID`.
  final String name;

  /// The token that starts a line comment in the file, e.g. `#` or `//`.
  final String comment;

  /// Creates the marker of the region called [name], for a file whose line
  /// comments start with [comment].
  const RegionMarker(this.name, {required this.comment});

  /// The line that opens the region.
  String get begin =>
      '$comment ----- BEGIN $name (autogenerated by flutter_flavorizr) -----';

  /// The line that closes the region.
  String get end =>
      '$comment ----- END $name (autogenerated by flutter_flavorizr) -----';

  @override
  String toString() => 'RegionMarker($name)';
}

/// A line of a source: where it starts, where its text ends and where it ends
/// once the line break is included.
final class TextLine {
  /// The position of the line, from 0.
  final int index;

  /// The offset of the first character of the line.
  final int start;

  /// The offset where the text of the line ends, before its line break.
  final int contentEnd;

  /// The offset where the line ends, its line break included.
  final int end;

  /// The text of the line, with no line break.
  final String text;

  /// The line break that ends the line, empty for the last line of a file
  /// without one.
  final String eol;

  /// Creates a line.
  const TextLine(
    this.index,
    this.start,
    this.contentEnd,
    this.end,
    this.text,
    this.eol,
  );

  /// The whitespace the line starts with.
  String get indentation =>
      text.substring(0, text.length - text.trimLeft().length);
}

/// The lines of a region, from the one with the begin marker ([first]) to the
/// one with the end marker ([last]), both included.
final class _Region {
  final RegionMarker marker;
  final int first;
  final int last;

  const _Region(this.marker, this.first, this.last);
}

/// A text file that has regions flavorizr owns, and the format preserving edits
/// that can be made to them.
///
/// The file belongs to the user. Whatever is outside the regions is written
/// back byte for byte, whatever its line endings, and only the regions of the
/// [markers] are ever touched.
///
/// Every edit returns the new text and leaves the instance as it was.
final class MarkedText {
  /// The text.
  final String source;

  /// The markers of the regions flavorizr owns in the file.
  final List<RegionMarker> markers;

  /// Every line of [source]. They put together give [source] back.
  final List<TextLine> lines;

  /// Creates the view of [source] that edits the regions of [markers].
  MarkedText(this.source, this.markers) : lines = _split(source);

  /// The line ending of the file, which is the first one it has: CRLF when it
  /// starts with one, LF otherwise.
  String get eol {
    final lf = source.indexOf('\n');

    return lf > 0 && source[lf - 1] == '\r' ? '\r\n' : '\n';
  }

  /// The lines that are not in a region of any of the [markers].
  ///
  /// It is where an anchor is looked for: the region of a previous run is never
  /// the anchor of the next one. Throws a [MalformedResourceException] when the
  /// markers do not form regions.
  List<TextLine> get outside {
    final inside = {
      for (final region in _regions(markers))
        for (var i = region.first; i <= region.last; i++) i,
    };

    return [
      for (final line in lines)
        if (!inside.contains(line.index)) line,
    ];
  }

  /// Returns the source with the region of [marker] holding [body].
  ///
  /// [body] is what is between the markers, one entry for each line, indented
  /// relative to the markers.
  ///
  /// * Up to date (one region that has the expected lines, whatever their
  ///   indentation): the source is returned as it is.
  /// * Not up to date: the first region is replaced in place, with its
  ///   indentation, and the other ones are dropped. The region stays where the
  ///   user left it.
  /// * Absent: a new region is inserted right after the line [anchor] picks
  ///   among the lines [outside], with the indentation of that line, or with
  ///   [indentation] when it is given. Nothing else is added: not even a blank
  ///   line goes outside of the markers.
  ///
  /// Throws a [MalformedResourceException] when the markers do not form
  /// regions, and when there is no region and [anchor] returns `null`.
  String upsert(
    RegionMarker marker,
    List<String> body, {
    required TextLine? Function(List<TextLine> outside) anchor,
    String? indentation,
  }) {
    final regions = _regions([marker]);

    if (regions.isEmpty) {
      final line = anchor(outside);

      if (line == null) throw MalformedResourceException(source);

      return _insert(
        line,
        _block(marker, body, indentation ?? line.indentation),
      );
    }

    final first = regions.first;
    final expected = [
      marker.begin,
      ...body.map((line) => line.trim()),
      marker.end,
    ]..removeWhere((line) => line.isEmpty);
    final actual = [
      for (final line in lines.sublist(first.first, first.last + 1))
        line.text.trim(),
    ]..removeWhere((line) => line.isEmpty);

    if (regions.length == 1 &&
        actual.length == expected.length &&
        actual.indexed.every((entry) => entry.$2 == expected[entry.$1])) {
      return source;
    }

    final edits = <(int, int, String)>[
      (
        lines[first.first].start,
        lines[first.last].contentEnd,
        _block(marker, body, lines[first.first].indentation).join(eol),
      ),
      for (final region in regions.skip(1))
        (lines[region.first].start, lines[region.last].end, ''),
    ];

    return _apply(edits);
  }

  /// Returns the source without the regions of [marker], each from the start of
  /// its first line to the end of its last one, line break included.
  String remove(RegionMarker marker) => _apply([
    for (final region in _regions([marker]))
      (lines[region.first].start, lines[region.last].end, ''),
  ]);

  /// Returns the content of [source] flavorizr owns, which is the lines of the
  /// regions of [markers], trimmed and joined with `\n`, or an empty string
  /// when there is none. It is what the lock hashes, so that whatever else the
  /// user edits, and the indentation or the line endings of the regions, are
  /// never drift.
  ///
  /// It does not throw when the markers do not form regions, since that is
  /// something the user did to the owned part: the marker lines that are there
  /// are the owned content, which differs from what the lock recorded.
  static String ownedContent(String source, List<RegionMarker> markers) {
    final text = MarkedText(source, markers);

    try {
      return [
        for (final region in text._regions(markers))
          for (final line in text.lines.sublist(region.first, region.last + 1))
            line.text.trim(),
      ].join('\n');
    } on MalformedResourceException {
      final owned = {
        for (final marker in markers) ...[marker.begin, marker.end],
      };

      return [
        '<unbalanced markers>',
        for (final line in text.lines)
          if (owned.contains(line.text.trim())) line.text.trim(),
      ].join('\n');
    }
  }

  List<String> _block(
    RegionMarker marker,
    List<String> body,
    String indentation,
  ) => [
    for (final line in [marker.begin, ...body, marker.end])
      line.isEmpty ? line : '$indentation$line',
  ];

  String _insert(TextLine anchor, List<String> block) => source.replaceRange(
    anchor.end,
    anchor.end,
    // An anchor that ends the file may have no line break: the block needs one
    // before it, and does not get one after it, so that the file still ends the
    // way it did.
    anchor.eol.isEmpty ? '$eol${block.join(eol)}' : '${block.join(eol)}$eol',
  );

  /// Applies edits, which are ranges of [source] and what replaces them, from
  /// the end, so that the offsets of the ones still to apply hold.
  String _apply(List<(int, int, String)> edits) {
    final ordered = [...edits]..sort((a, b) => b.$1.compareTo(a.$1));

    return ordered.fold(
      source,
      (text, edit) => text.replaceRange(edit.$1, edit.$2, edit.$3),
    );
  }

  /// The regions of [of], in order. Throws a [MalformedResourceException] when
  /// the markers do not form regions: they are the user's to fix, and are never
  /// guessed.
  List<_Region> _regions(List<RegionMarker> of) {
    final regions = <_Region>[];

    for (final marker in of) {
      int? open;

      for (final line in lines) {
        final text = line.text.trim();

        if (text == marker.begin) {
          if (open != null) throw MalformedResourceException(source);

          open = line.index;
        } else if (text == marker.end) {
          if (open == null) throw MalformedResourceException(source);

          regions.add(_Region(marker, open, line.index));
          open = null;
        }
      }

      if (open != null) throw MalformedResourceException(source);
    }

    return regions..sort((a, b) => a.first.compareTo(b.first));
  }

  /// Splits [source] in lines. Every character belongs to exactly one line, so
  /// the lines can be put back together to get [source].
  static List<TextLine> _split(String source) {
    final lines = <TextLine>[];
    var start = 0;

    while (start < source.length) {
      final lf = source.indexOf('\n', start);
      final end = lf < 0 ? source.length : lf + 1;
      var contentEnd = lf < 0 ? source.length : lf;

      if (lf > start && source[lf - 1] == '\r') contentEnd = lf - 1;

      lines.add(
        TextLine(
          lines.length,
          start,
          contentEnd,
          end,
          source.substring(start, contentEnd),
          source.substring(contentEnd, end),
        ),
      );
      start = end;
    }

    return lines;
  }
}
