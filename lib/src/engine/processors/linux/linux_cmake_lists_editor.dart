import 'package:flutter_flavorizr/src/engine/processors/linux/marked_text.dart';
import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';
import 'package:flutter_flavorizr/src/utils/desktop_utils.dart';

/// The edits flavorizr makes to `linux/CMakeLists.txt`.
///
/// The file belongs to the user. The only part flavorizr owns is a *marked
/// region* that overrides `APPLICATION_ID` for each flavor, right after the
/// directory of Flutter is added:
///
/// ```cmake
/// # ----- BEGIN APPLICATION_ID (autogenerated by flutter_flavorizr) -----
/// if(DEFINED FLUTTER_APP_FLAVOR)
///   if(FLUTTER_APP_FLAVOR STREQUAL "apple")
///     set(APPLICATION_ID "com.example.apple")
///   endif()
/// endif()
/// # ----- END APPLICATION_ID (autogenerated by flutter_flavorizr) -----
/// ```
///
/// The markers are the ones 2.x writes. Everything outside the region is
/// written back byte for byte, and a region that is already there is
/// regenerated where it is, so that a flavor that was dropped from the
/// configuration is not in it anymore. See [MarkedText.upsert].
abstract final class LinuxCMakeListsEditor {
  /// The markers of the region.
  static const RegionMarker marker = RegionMarker(
    'APPLICATION_ID',
    comment: '#',
  );

  static final RegExp _applicationIdSetter = RegExp(
    r'set\(APPLICATION_ID "[^"]*"\)',
  );

  static const String _flutterManagedDirAnchor =
      r'add_subdirectory(${FLUTTER_MANAGED_DIR})';

  /// Returns [source] with the region up to date for [applicationIds], the
  /// application id of each flavor by name.
  ///
  /// Throws a [MalformedResourceException] when [source], leaving the region
  /// out, has no `set(APPLICATION_ID "...")` or no
  /// `add_subdirectory(${FLUTTER_MANAGED_DIR})`, or when the markers do not
  /// form a region.
  static String withApplicationIds(
    String source,
    Map<String, String> applicationIds,
  ) {
    final text = MarkedText(source, [marker]);
    final outside = text.outside;

    if (!outside.any((line) => _applicationIdSetter.hasMatch(line.text))) {
      throw MalformedResourceException(source);
    }

    return text.upsert(
      marker,
      _body(applicationIds),
      anchor: (lines) => lines
          .where((line) => line.text.contains(_flutterManagedDirAnchor))
          .firstOrNull,
    );
  }

  /// Returns the content of [source] flavorizr owns, which is the region. It is
  /// what the lock hashes. See [MarkedText.ownedContent].
  static String ownedContent(String source) =>
      MarkedText.ownedContent(source, [marker]);

  static List<String> _body(Map<String, String> applicationIds) {
    final entries = applicationIds.entries.toList(growable: false);

    return [
      'if(DEFINED FLUTTER_APP_FLAVOR)',
      for (final (index, entry) in entries.indexed) ...[
        '  ${index == 0 ? 'if' : 'elseif'}(FLUTTER_APP_FLAVOR STREQUAL "${entry.key}")',
        '    set(APPLICATION_ID "${escapeQuotedString(entry.value)}")',
      ],
      if (entries.isNotEmpty) '  endif()',
      'endif()',
    ];
  }
}
