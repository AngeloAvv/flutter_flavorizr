import 'package:flutter_flavorizr/src/exception/existing_flavor_dimensions_exception.dart';
import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';

/// The build script language of `android/app/build.gradle(.kts)`, which decides
/// how the flavors file is applied.
enum BuildGradleDsl {
  /// `build.gradle`.
  groovy(
    flavorsFile: 'flavorizr.gradle',
    applyStatement: 'apply from: "flavorizr.gradle"',
    unmarkedApply: r'''apply\s+from:\s*(["'])flavorizr\.gradle\1;?''',
  ),

  /// `build.gradle.kts`.
  kotlin(
    flavorsFile: 'flavorizr.gradle.kts',
    applyStatement: 'apply { from("flavorizr.gradle.kts") }',
    unmarkedApply:
        r'apply\s*\{\s*from\(\s*"flavorizr\.gradle\.kts"\s*\)\s*\};?'
        r'|apply\(\s*from\s*=\s*"flavorizr\.gradle\.kts"\s*\);?',
  );

  /// The name of the flavors file the build file applies, which is a sibling.
  final String flavorsFile;

  /// The statement that applies [flavorsFile].
  final String applyStatement;

  final String _unmarkedApply;

  const BuildGradleDsl({
    required this.flavorsFile,
    required this.applyStatement,
    required String unmarkedApply,
  }) : _unmarkedApply = unmarkedApply;

  /// Matches a whole line (trimmed) that applies [flavorsFile] with nothing
  /// else on it. See [AndroidBuildGradleEditor.withFlavorizrRegion].
  RegExp get unmarkedApply => RegExp('^(?:$_unmarkedApply)\$');
}

/// The edits flavorizr makes to `android/app/build.gradle(.kts)`.
///
/// The build file belongs to the user. The only part flavorizr owns is a
/// *marked region*, three lines that apply the flavors file the flavorizr
/// gradle processor writes:
///
/// ```groovy
/// // ----- BEGIN flavorDimensions (autogenerated by flutter_flavorizr) -----
/// apply from: "flavorizr.gradle"
/// // ----- END flavorDimensions (autogenerated by flutter_flavorizr) -----
/// ```
///
/// The markers are the ones 2.x writes, so a project that was flavorized by a
/// 2.x run is recognized and nothing is duplicated. A marker is a whole line,
/// whatever its indentation and line ending.
///
/// Everything outside the region is written back byte for byte. What happens to
/// the region:
///
/// * Up to date (one region that has the expected lines, wherever it is): the
///   source is returned as it is.
/// * Not up to date, for example a region of an older version that declared the
///   flavors in the build file, or of the other DSL, or duplicated: every
///   region is removed and a new one is appended at the end of the file, like
///   2.x does. A region cannot stay where it was: the old one may sit inside
///   the `android` block, where `apply from` is not valid.
/// * Absent: when a line applies the flavors file with nothing else on it,
///   written by hand or by a 2.x run that predates the markers, the first one
///   is *adopted*, which means that it is replaced in place, indentation
///   included, by the region. Applying the same file twice would declare the
///   flavors twice, and the line is exactly what the region says, so it is the
///   safe choice. A commented line, a line that applies another file or that
///   has anything else on it is not adopted and is left alone. Otherwise the
///   region is appended.
abstract final class AndroidBuildGradleEditor {
  static const String _begin =
      '// ----- BEGIN flavorDimensions (autogenerated by flutter_flavorizr) -----';
  static const String _end =
      '// ----- END flavorDimensions (autogenerated by flutter_flavorizr) -----';

  static const String _androidEntryPoint = 'android {';
  static const String _flavorDimensions = 'flavorDimensions';

  static List<String> _expectedRegion(BuildGradleDsl dsl) => [
    _begin,
    dsl.applyStatement,
    _end,
  ];

  /// Returns [source] with the region of flavorizr up to date for [dsl].
  ///
  /// Throws a [MalformedResourceException] when [source] has no `android {`
  /// block, and an [ExistingFlavorDimensionsException] when it declares
  /// `flavorDimensions` and has no region, or when the markers do not form
  /// regions: that is flavor configuration of the user, which cannot be told
  /// apart from the one of flavorizr, and it is never touched.
  static String withFlavorizrRegion(String source, BuildGradleDsl dsl) {
    if (!source.contains(_androidEntryPoint)) {
      throw MalformedResourceException(source);
    }

    final lines = _lines(source);
    final regions = _regions(source, lines);
    final expected = _expectedRegion(dsl);

    if (regions.length == 1 && _matches(lines, regions.single, expected)) {
      return source;
    }

    if (regions.isEmpty) {
      if (source.contains(_flavorDimensions)) {
        throw ExistingFlavorDimensionsException(source);
      }

      final adoptable = lines
          .where((line) => dsl.unmarkedApply.hasMatch(line.text.trim()))
          .firstOrNull;

      if (adoptable != null) {
        final indentation = adoptable.text.substring(
          0,
          adoptable.text.length - adoptable.text.trimLeft().length,
        );
        final eol = _lineEnding(source);

        return source.replaceRange(
          adoptable.start,
          adoptable.contentEnd,
          [for (final line in expected) '$indentation$line'].join(eol),
        );
      }
    }

    return _append(_without(source, lines, regions), expected, source);
  }

  /// Returns the content of [source] flavorizr owns: the lines of the region,
  /// trimmed and joined with `\n`, or an empty string when there is none. It is
  /// what the lock hashes for the build file, so that whatever else the user
  /// edits, and the indentation or the line endings of the region, are never
  /// drift.
  ///
  /// Throws an [ExistingFlavorDimensionsException] when the markers do not form
  /// regions.
  static String ownedContent(String source) {
    final lines = _lines(source);

    return [
      for (final region in _regions(source, lines))
        for (final line in lines.sublist(region.first, region.last + 1))
          line.text.trim(),
    ].join('\n');
  }

  static String _append(String text, List<String> region, String original) {
    final eol = _lineEnding(original);

    return [
      text,
      if (text.isNotEmpty && !text.endsWith('\n')) eol,
      region.join(eol),
    ].join();
  }

  static bool _matches(
    List<_Line> lines,
    _Region region,
    List<String> expected,
  ) {
    final actual = [
      for (final line in lines.sublist(region.first, region.last + 1))
        line.text.trim(),
    ];

    return actual.length == expected.length &&
        actual.indexed.every((entry) => entry.$2 == expected[entry.$1]);
  }

  /// [source] without [regions], each from the start of its first line to the
  /// end of its last one, line break included.
  static String _without(
    String source,
    List<_Line> lines,
    List<_Region> regions,
  ) {
    // From the end, so that the offsets of the regions still to remove hold.
    return regions.reversed.fold(
      source,
      (text, region) => text.replaceRange(
        lines[region.first].start,
        lines[region.last].end,
        '',
      ),
    );
  }

  /// The regions delimited by the markers, as ranges of lines, in order.
  static List<_Region> _regions(String source, List<_Line> lines) {
    final regions = <_Region>[];
    int? open;

    for (final (index, line) in lines.indexed) {
      final text = line.text.trim();

      if (text == _begin) {
        if (open != null) throw ExistingFlavorDimensionsException(source);

        open = index;
      } else if (text == _end) {
        if (open == null) throw ExistingFlavorDimensionsException(source);

        regions.add(_Region(open, index));
        open = null;
      }
    }

    if (open != null) throw ExistingFlavorDimensionsException(source);

    return regions;
  }

  /// The line ending of the file, which is the first one it has: CRLF when it
  /// starts with one, LF otherwise.
  static String _lineEnding(String source) {
    final lf = source.indexOf('\n');

    return lf > 0 && source[lf - 1] == '\r' ? '\r\n' : '\n';
  }

  /// Splits [source] in lines. Every character belongs to exactly one line, so
  /// the lines can be put back together to get [source].
  static List<_Line> _lines(String source) {
    final lines = <_Line>[];
    var start = 0;

    while (start < source.length) {
      final lf = source.indexOf('\n', start);
      final end = lf < 0 ? source.length : lf + 1;
      var contentEnd = lf < 0 ? source.length : lf;

      if (lf > start && source[lf - 1] == '\r') contentEnd = lf - 1;

      lines.add(
        _Line(start, contentEnd, end, source.substring(start, contentEnd)),
      );
      start = end;
    }

    return lines;
  }
}

/// A line of a source: where it starts, where its text ends and where it ends
/// once the line break is included.
final class _Line {
  final int start;
  final int contentEnd;
  final int end;
  final String text;

  const _Line(this.start, this.contentEnd, this.end, this.text);
}

/// The lines of a region, from the one with the begin marker ([first]) to the
/// one with the end marker ([last]), both included.
final class _Region {
  final int first;
  final int last;

  const _Region(this.first, this.last);
}
