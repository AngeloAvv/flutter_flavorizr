final _storyboardPath = RegExp(
  '^Runner/$flavorNameCharacter+LaunchScreen\\.storyboard\$',
);

/// The part of the `project.pbxproj` of iOS that the references to the
/// storyboards of `ios:launchScreen` make up, which the lock hashes for it: the
/// definitions of the references to `Runner/<flavor>LaunchScreen.storyboard`,
/// and the entries that put them in a Resources phase.
///
/// A reference to a storyboard of the user that is named like the ones of the
/// flavors, in this folder, is taken for one of them.
String launchScreenReferencesOwnedContent(String source) =>
    referencesOwnedContent(source, _storyboardPath.hasMatch);

/// `ios:launchScreen`: the launch screen of each iOS flavor that has one (see
/// `FlavorizrConfig.launchScreenOf`), made from its icon.
///
/// For every such flavor:
///
/// * `ios/Runner/<flavor>LaunchScreen.storyboard`: the image of the flavor
///   centred on the system background colour, generated in code;
/// * `ios/Runner/Assets.xcassets/<flavor>LaunchImage.imageset`: the image, at
///   the three scales. It is the icon the flavor has, with its badge when the
///   flavor has one (see `FlavorizrConfig.badgeOf`): the `icon` of the iOS
///   platform or of the app and, when there is none, or the flavor has a badge,
///   the source the badge is drawn on (the `icon` of the root, then the
///   `AppIcon` of the project);
/// * a reference to the storyboard in the project, which is a resource of the
///   app.
///
/// `UILaunchStoryboardName` is not set here. It is `$(LAUNCH_SCREEN_NAME)`,
/// which `ios:plist` writes and `ios:xcconfig` defines in each flavor, so that
/// the launch screen is a property of the flavor and not of the processors of
/// the run.
///
/// The files are [Artifact.managed]: they are generated whole, so they are
/// hashed in the lock, a hand edit of them is a conflict, and the ones of a
/// flavor that has no launch screen anymore are removed by the reconciliation of
/// stale artifacts, with the folders that leaves empty. What 2.x made is the
/// user's: a storyboard that exists, and does not say it was generated by
/// flavorizr, is never overwritten or deleted, and neither is the imageset of
/// the flavor (an imageset on its own, with a storyboard of flavorizr, is just
/// as safe). The reference to a storyboard is **owned** (`OwnedObjects`) when
/// flavorizr made it, and removed with it.
///
/// Everything is read and rendered before the first file is written, so a
/// missing or broken icon leaves the workspace untouched.
class IosLaunchScreenProcessor extends FlavorizrProcessor {
  /// Creates the processor.
  const IosLaunchScreenProcessor();

  @override
  String get id => 'ios:launchScreen';

  @override
  Set<ResourceKey<Object?>> get requires => {XcodeprojResource.iosKey};

  @override
  Future<void> apply(FlavorizrContext ctx) async {
    final owned = OwnedObjects.ios(ctx);
    final outputs = <String, List<int>>{};
    final storyboards = <String>[];

    for (final MapEntry(key: flavor, value: definition)
        in ctx.config.launchScreenFlavors.entries) {
      checkFlavorName(flavor);

      final storyboard = '${K.iOSRunnerPath}/${flavor}LaunchScreen.storyboard';

      if (!_isFlavorizrs(ctx, storyboard, isGeneratedLaunchScreen)) {
        ctx.logger.info(
          'The launch screen `$storyboard` is not one of flavorizr: it is the '
          'one the flavor `$flavor` uses, and it is left as it is.',
        );

        continue;
      }

      storyboards.add(flavor);
      outputs[storyboard] = utf8.encode(launchScreenStoryboard(flavor));

      final imageset = '${K.iOSAssetsPath}/${flavor}LaunchImage.imageset';

      if (!_isFlavorizrs(
        ctx,
        '$imageset/Contents.json',
        isGeneratedLaunchImage,
      )) {
        ctx.logger.info(
          'The image `$imageset` is not one of flavorizr: it is the one the '
          'launch screen of the flavor `$flavor` shows, and it is left as it '
          'is.',
        );

        continue;
      }

      outputs['$imageset/Contents.json'] = utf8.encode(launchImageContents);

      final images = await _render(ctx, flavor, definition);

      for (final MapEntry(key: name, value: png) in images.entries) {
        outputs['$imageset/$name'] = png;
      }
    }

    for (final MapEntry(key: path, value: content) in outputs.entries) {
      final target = File(ctx.resolve(path));

      await target.parent.create(recursive: true);
      await target.writeAsBytes(content);
      ctx.track(Artifact.managed(path));
    }

    for (final flavor in storyboards) {
      _ensureStoryboard(owned, flavor);
    }

    owned.settle();

    ctx.track(XcodeprojResource.iosArtifact);
  }

  /// Whether the file at [path], a path of the project, is flavorizr's to
  /// write: it is not there, or it is and [isGenerated] says it was generated.
  static bool _isFlavorizrs(
    FlavorizrContext ctx,
    String path,
    bool Function(String text) isGenerated,
  ) {
    final file = File(ctx.resolveProject(path));

    if (!file.existsSync()) return true;

    try {
      return isGenerated(file.readAsStringSync());
    } on FormatException {
      // Not text: it is not one flavorizr made.
      return false;
    }
  }

  /// The images of the launch screen of [flavor], by file name: its icon, with
  /// its badge, at the size of each scale.
  static Future<Map<String, Uint8List>> _render(
    FlavorizrContext ctx,
    String flavor,
    Flavor definition,
  ) async {
    final badge = ctx.config.badgeOf(flavor);
    final icon = definition.ios?.icon ?? definition.app.icon;
    final String source;

    if (badge == null && icon != null) {
      source = icon;
    } else {
      try {
        source = resolveBadgeSourceIcon(
          flavorIcon: icon,
          rootIcon: ctx.config.icon,
          files: ProjectBadgeSourceFiles(ctx.projectRoot),
        ).path;
      } on BadgeSourceIconException catch (error) {
        throw InvalidConfigurationException(
          'The flavor `$flavor` has a launch screen, and there is no icon to '
          'make it from: set `icon` for the flavor, or `icon` at the root '
          '(1024 px is best). ${_looked(error)}',
        );
      }
    }

    final image = await loadIconSource(ctx, source);

    return {
      for (final MapEntry(key: name, value: size) in launchImageSizes.entries)
        name: image.renderPng(size, size, badge: badge),
    };
  }

  static String _looked(BadgeSourceIconException error) => error.tried.isEmpty
      ? 'No icon was found in the project.'
      : 'Looked at: ${error.tried.join(', ')}.';

  /// Makes sure the project has the storyboard of [flavor], as a resource of
  /// the app.
  ///
  /// A reference to the file that is in the project already (2.x made it, or
  /// the user) is used as it is, and never removed: it is foreign, unless the
  /// lock recorded it. The new one is in the main group, with the path of the
  /// file from the project (`Runner/<flavor>LaunchScreen.storyboard`) as 2.x
  /// wrote it, and its UUIDs come from the flavor, so two runs from scratch
  /// write the same project.
  static void _ensureStoryboard(OwnedObjects owned, String flavor) {
    final project = owned.project;
    final path = p.posix.relative(
      '${K.iOSRunnerPath}/${flavor}LaunchScreen.storyboard',
      from: K.iOSPath,
    );

    final reference = owned.ensure<PBXFileReference>(
      (g, u) => PBXFileReference(g, u),
      flavor: flavor,
      kind: const ['launchScreenFileReference'],
      existing: () =>
          project.files.where((file) => file.path == path).firstOrNull,
      create: (file) {
        file.path = path;
        file.sourceTree = '<group>';
        file.lastKnownFileType = 'file.storyboard';
        project.mainGroup.children.add(file);
      },
    );

    // A reference that was there is in the phase it was put in.
    if (!owned.owned.contains(reference.uuid)) return;

    final target = project.targets.first as PBXNativeTarget;

    owned.ensure<PBXBuildFile>(
      (g, u) => PBXBuildFile(g, u),
      flavor: flavor,
      kind: const ['launchScreenBuildFile'],
      existing: () => target.resourcesBuildPhase.buildFile(reference),
      create: (file) {
        file.fileRef = reference;
        target.resourcesBuildPhase.files.add(file);
      },
    );
  }
}
