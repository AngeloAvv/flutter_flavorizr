import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';
import 'package:flutter_flavorizr/src/exception/unsafe_podfile_exception.dart';
import 'package:flutter_flavorizr/src/extensions/extensions_string.dart';
import 'package:flutter_flavorizr/src/parser/models/flavors/darwin/enums.dart';

/// The edits flavorizr makes to the Podfile of the iOS and macOS projects.
///
/// The file belongs to the user. The only part flavorizr owns is a *marked
/// region* inside the mapping of build configurations, which CocoaPods needs to
/// know what each configuration of the project is:
///
/// ```ruby
/// project 'Runner', {
///   # ----- BEGIN flavorizr (autogenerated by flutter_flavorizr) -----
///   'Debug-apple' => :debug,
///   'Profile-apple' => :release,
///   'Release-apple' => :release,
///   # ----- END flavorizr (autogenerated by flutter_flavorizr) -----
///   'Debug' => :debug,
///   'Profile' => :release,
///   'Release' => :release,
/// }
/// ```
///
/// Everything outside the region is written back byte for byte, and a region
/// that is already there is regenerated where it is, so that a flavor that was
/// dropped from the configuration is not in it anymore. See
/// [MarkedText.upsert].
///
/// **The default mappings stay.** 2.x replaced the mapping, so a Podfile it had
/// flavorized has no `Debug`, `Profile` and `Release`, which the default
/// configurations of the project still need. A default mapping that is not
/// outside the region is written inside it, and goes when the user writes it
/// outside.
///
/// **A Podfile flavorized by 2.x is adopted.** 2.x wrote the mappings with no
/// markers, right after the opening line. When there is no region yet, the
/// lines of the mapping that are exactly the ones the region would hold are
/// taken in: the first one is replaced in place by the region, and the other
/// ones are dropped, since the region says the same. A line that is not exactly
/// one of them (another flavor, another mode) is the user's and stays.
///
/// **The layout is not guessed.** The Podfile is Ruby, and the editor does not
/// parse it: it is anchored to a few lines, and refuses what it cannot tell
/// safely with an [UnsafePodfileException]. It needs
///
/// * exactly one line `project 'Runner', {` (or with double quotes), with
///   nothing after the brace, outside of comments, heredocs and `=begin` blocks;
/// * a mapping that goes on until a line with only `}`, and has nothing but
///   blank lines, comments and entries like `'Debug' => :debug,`, one on each
///   line (the last one may have no comma, any may have a comment after it);
/// * markers, when there are any, that form a region in the mapping, and are
///   not in a heredoc or a `=begin` block.
///
/// Anything else in the Podfile (`target`, `post_install`, the rest) is not
/// interpreted, so it can be written in any way. The editor only skips the
/// bodies of heredocs (`<<~EOS`, `<<-EOS`, `<<EOS`) and `=begin` blocks when it
/// looks for the mapping line and the markers, and a `<<WORD` that is not
/// preceded by a word character is taken for a heredoc even when it is not one
/// (a `<<` after a space in a comment at the end of a line, for instance), so
/// that one with no closing line is refused. A string that goes over several
/// lines is not told from code.
abstract final class PodfileEditor {
  /// The markers of the region.
  static const RegionMarker marker = RegionMarker('flavorizr', comment: '#');

  // The line that opens the mapping, and what a line of it is.
  static final RegExp _opening = RegExp(
    r"""^\s*project\s+(['"])Runner\1\s*,\s*\{\s*$""",
  );
  static final RegExp _entry = RegExp(
    r"""^(['"])((?:\\.|(?!\1)[^\\])+)\1\s*=>\s*:\w+\s*,?\s*(?:#.*)?$""",
  );
  static final RegExp _heredoc = RegExp(
    r"""(?<!\w)<<([~-]?)(['"`]?)([A-Za-z_]\w*)\2""",
  );

  /// Returns [source], the content of the Podfile at [path], with the region up
  /// to date for [flavors], the names of the flavors of the platform.
  ///
  /// Throws an [UnsafePodfileException] when [source] has a layout the editor
  /// does not support (see [PodfileEditor]): nothing is guessed.
  static String withFlavorMappings(
    String source,
    Iterable<String> flavors, {
    required String path,
  }) {
    final text = MarkedText(source, [marker]);
    final nonCode = _nonCodeLines(text.lines, path);

    for (final line in text.lines) {
      if (nonCode.contains(line.index) &&
          (line.text.trim() == marker.begin ||
              line.text.trim() == marker.end)) {
        throw _unsafe(
          path,
          'a flavorizr marker is inside a heredoc or a block comment, where it '
              'cannot be told from text.',
          'Move the marker lines out of it, or remove them.',
        );
      }
    }

    final List<TextLine> outside;

    try {
      outside = text.outside;
    } on MalformedResourceException {
      throw _unsafe(
        path,
        'its flavorizr markers do not form a region: one `BEGIN` has no `END` '
            'after it, or the other way around.',
        'Remove the lines `${marker.begin}` and `${marker.end}`, or leave '
            'one pair.',
      );
    }

    final mapping = _mappingOf(text, outside, nonCode, path);
    final present = {for (final (_, key) in mapping.entries) key};
    final defaults = [
      for (final target in Target.values)
        if (!present.contains(target.name.capitalize)) _entryOf(target, null),
    ];
    final mappings = [
      for (final flavor in flavors)
        for (final target in Target.values) _entryOf(target, flavor),
    ];
    final body = [...defaults, ...mappings];

    if (mapping.hasRegion) {
      return body.isEmpty
          ? text.remove(marker)
          : text.upsert(marker, body, anchor: (lines) => mapping.anchor);
    }

    if (mappings.isEmpty) return source;

    // What 2.x wrote: the lines that are what the region holds, no more.
    final written = mappings.toSet();
    final adopted = [
      for (final (line, _) in mapping.entries)
        if (written.contains(line.text.trim())) line,
    ];
    final first = adopted.firstOrNull;
    final edited = MarkedText(
      adopted.reversed.fold(
        source,
        (text, line) => text.replaceRange(line.start, line.end, ''),
      ),
      [marker],
    );
    final after = first == null ? mapping.anchor.index : first.index - 1;

    return edited.upsert(
      marker,
      body,
      anchor: (lines) => lines.where((line) => line.index == after).first,
      indentation:
          (first ?? mapping.entries.firstOrNull?.$1)?.indentation ??
          '${mapping.anchor.indentation}  ',
    );
  }

  /// Returns the content of [source] flavorizr owns, which is the region. It is
  /// what the lock hashes. See [MarkedText.ownedContent].
  static String ownedContent(String source) =>
      MarkedText.ownedContent(source, [marker]);

  static UnsafePodfileException _unsafe(
    String path,
    String reason,
    String fix,
  ) => UnsafePodfileException(path, reason: reason, fix: fix);

  /// Finds the mapping in [text], whose lines [outside] of the region are the
  /// ones that count, and checks that it has the layout the editor supports.
  static _Mapping _mappingOf(
    MarkedText text,
    List<TextLine> outside,
    Set<int> nonCode,
    String path,
  ) {
    final outsideLines = {for (final line in outside) line.index};
    final openings = [
      for (final line in outside)
        if (!nonCode.contains(line.index) && _opening.hasMatch(line.text)) line,
    ];

    if (openings.length != 1) {
      throw _unsafe(
        path,
        openings.isEmpty
            ? "it has no line `project 'Runner', {` that opens the mapping of "
                  'the build configurations.'
            : "it has the line `project 'Runner', {` twice.",
        "Keep one mapping, written one entry on each line: `project 'Runner', "
        "{`, then `'Debug' => :debug,`, `'Profile' => :release,` and "
        "`'Release' => :release,`, then `}`.",
      );
    }

    final anchor = openings.single;
    final entries = <(TextLine, String)>[];
    TextLine? close;

    for (final line in text.lines.skip(anchor.index + 1)) {
      final trimmed = line.text.trim();

      if (!outsideLines.contains(line.index)) continue;

      if (trimmed == '}') {
        close = line;
        break;
      }

      if (trimmed.isEmpty || trimmed.startsWith('#')) continue;

      final entry = _entry.firstMatch(trimmed);

      if (entry == null) {
        throw _unsafe(
          path,
          'the mapping has a line that is not one entry like '
              "`'Debug' => :debug,`: `$trimmed`.",
          'Write the mapping one entry on each line, and close it with a line '
              'that has only `}`.',
        );
      }

      entries.add((line, entry[2]!));
    }

    if (close == null) {
      throw _unsafe(
        path,
        'the mapping is not closed: there is no line with only `}` after it.',
        'Close the mapping with a line that has only `}`.',
      );
    }

    final region = text.lines.where(
      (line) => !outsideLines.contains(line.index),
    );

    if (region.any(
      (line) => line.index < anchor.index || line.index > close!.index,
    )) {
      throw _unsafe(
        path,
        'the flavorizr region is outside of the mapping.',
        'Remove the lines of the region, or move them into the mapping.',
      );
    }

    return _Mapping(anchor, entries, hasRegion: region.isNotEmpty);
  }

  /// The mapping of [target] for [flavor], or the default one without it.
  static String _entryOf(Target target, String? flavor) {
    final name = target.name.capitalize;
    final configuration = flavor == null
        ? name
        : '$name-${flavor.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}';

    return "'$configuration' => :${target.darwinTarget},";
  }

  /// The lines where code is not: the bodies of heredocs, and `=begin` blocks.
  /// A heredoc that is never closed is refused.
  static Set<int> _nonCodeLines(List<TextLine> lines, String path) {
    final nonCode = <int>{};
    final pending = <({String id, bool indented})>[];
    var block = false;

    for (final line in lines) {
      final text = line.text;

      if (block) {
        nonCode.add(line.index);
        block = !text.startsWith('=end');
      } else if (pending.isNotEmpty) {
        nonCode.add(line.index);

        final next = pending.first;

        if ((next.indented ? text.trim() : text) == next.id) {
          pending.removeAt(0);
        }
      } else if (text.startsWith('=begin')) {
        nonCode.add(line.index);
        block = true;
      } else if (!text.trimLeft().startsWith('#')) {
        for (final match in _heredoc.allMatches(text)) {
          pending.add((id: match[3]!, indented: match[1]!.isNotEmpty));
        }
      }
    }

    if (pending.isNotEmpty) {
      throw _unsafe(
        path,
        'a heredoc (`<<${pending.first.id}`) is never closed.',
        'Close it with a line that has only `${pending.first.id}`.',
      );
    }

    return nonCode;
  }
}

/// The mapping of a Podfile: the line that opens it, the entries it has outside
/// of the region, with the name of the configuration of each one, and whether
/// the region is in it.
final class _Mapping {
  final TextLine anchor;
  final List<(TextLine, String)> entries;
  final bool hasRegion;

  const _Mapping(this.anchor, this.entries, {required this.hasRegion});
}
