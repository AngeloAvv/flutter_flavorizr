import 'dart:convert';

/// The side, in points, of the icon the launch screen shows: its image has
/// this many pixels at 1x, twice that at 2x and three times at 3x.
const launchImagePoints = 128;

/// The image files of `<flavor>LaunchImage.imageset` with the side in pixels
/// each one has, by name.
const launchImageSizes = {
  'LaunchImage.png': launchImagePoints,
  'LaunchImage@2x.png': launchImagePoints * 2,
  'LaunchImage@3x.png': launchImagePoints * 3,
};

/// What tells a launch screen that flavorizr generated from the one 2.x copied,
/// or one the user made: only the first is flavorizr's to overwrite and delete.
const _storyboardMarker = '<!-- Generated by flutter_flavorizr';

/// The `info.author` of the `Contents.json` of a generated imageset: Xcode
/// writes `xcode`, which is what 2.x copied.
const _imagesetAuthor = 'flavorizr';

/// The placeholder of the name of the flavor in [_storyboard].
const _flavorName = '[[FLAVOR_NAME]]';

/// The launch screen of a flavor, `<flavor>LaunchScreen.storyboard`: its image,
/// `<flavor>LaunchImage`, centred on the system background colour, which is
/// white in the light appearance and black in the dark one.
String launchScreenStoryboard(String flavorName) =>
    _storyboard.replaceAll(_flavorName, _escape(flavorName));

/// Whether [storyboard], the text of a launch screen, is one flavorizr
/// generated: see [launchScreenStoryboard].
bool isGeneratedLaunchScreen(String storyboard) =>
    storyboard.contains(_storyboardMarker);

/// The `Contents.json` of `<flavor>LaunchImage.imageset`: an image for each of
/// the three scales, which are the keys of [launchImageSizes].
const launchImageContents =
    '''
{
  "images" : [
    {
      "idiom" : "universal",
      "filename" : "LaunchImage.png",
      "scale" : "1x"
    },
    {
      "idiom" : "universal",
      "filename" : "LaunchImage@2x.png",
      "scale" : "2x"
    },
    {
      "idiom" : "universal",
      "filename" : "LaunchImage@3x.png",
      "scale" : "3x"
    }
  ],
  "info" : {
    "version" : 1,
    "author" : "$_imagesetAuthor"
  }
}
''';

/// Whether [contents], the text of the `Contents.json` of an imageset, is one
/// flavorizr generated: see [launchImageContents].
bool isGeneratedLaunchImage(String contents) {
  try {
    final json = jsonDecode(contents);
    final info = json is Map ? json['info'] : null;

    return info is Map && info['author'] == _imagesetAuthor;
  } on FormatException {
    return false;
  }
}

String _escape(String text) => text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');

