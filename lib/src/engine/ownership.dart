/// Who owns an artifact, the file a processor produces, once it is in the
/// project.
///
/// Every tracked artifact has exactly one class, and it decides what a run may
/// do to the file (see `decideArtifactAction`) and whether the lock records a
/// hash for it ([isHashed]).
enum Ownership {
  /// Created once and never overwritten: it belongs to the user afterwards.
  ///
  /// A run writes a scaffold artifact only when the file does not exist, or
  /// when the user explicitly asks to overwrite scaffolds
  /// (`--overwrite-scaffold`). It is never hashed: whatever the user does to
  /// it is not drift.
  scaffold(isHashed: false),

  /// Fully regenerated by the tool. Users should not edit it.
  ///
  /// The whole file is hashed in the lock. A run rewrites it when the
  /// configuration changed, and reports a conflict when the file was edited by
  /// hand since the last run.
  managed(isHashed: true),

  /// Shared with the user: only marked regions or owned keys are touched, and
  /// everything else is preserved.
  ///
  /// Only the owned parts are hashed in the lock, so edits outside them are
  /// never drift. A run patches the owned parts when the configuration
  /// changed, and reports a conflict when the owned parts were edited by hand
  /// since the last run. A file the lock does not know yet is adopted by
  /// patching it, since everything outside the owned parts is preserved.
  patched(isHashed: true),

  /// Mutated by builds or usually ignored by git, such as `.idea/` run
  /// configurations, `.vscode/launch.json` or the Firebase files copied by a
  /// build script.
  ///
  /// It is regenerated silently on every run, never hashed, and so it is
  /// never a conflict and never drift, even after `flutter build`.
  local(isHashed: false);

  /// Whether the lock records a hash for artifacts of this class.
  ///
  /// Only hashed classes can be drifted from, or be in conflict.
  final bool isHashed;

  const Ownership({required this.isHashed});
}
