import 'package:flutter_flavorizr/src/engine/lock/flavorizr_lock.dart';
import 'package:flutter_flavorizr/src/engine/lock/lock_codec.dart';
import 'package:flutter_flavorizr/src/engine/ownership.dart';
import 'package:flutter_flavorizr/src/exception/malformed_lock_file_exception.dart';
import 'package:flutter_flavorizr/src/exception/unsupported_lock_version_exception.dart';
import 'package:flutter_test/flutter_test.dart';

void main() {
  group('LockCodec.encode', () {
    test('writes the version fields and the flavors, with sorted keys', () {
      final lock = FlavorizrLock(
        flavorizrVersion: '3.0.0',
        flavors: {'prod': 'sha256:bbb', 'dev': 'sha256:aaa'},
      );

      expect(
        LockCodec.encode(lock),
        '# flavorizr.lock: generated by flutter_flavorizr, do not edit.\n'
        '# Commit this file: it lets flavorizr remove what it generated.\n'
        'flavorizrVersion: 3.0.0\n'
        'flavors:\n'
        '  dev: sha256:aaa\n'
        '  prod: sha256:bbb\n'
        'processors: {}\n'
        'schemaVersion: 1\n',
      );
    });

    test('writes the files of a processor with class and hash, sorted', () {
      final lock = FlavorizrLock(
        flavorizrVersion: '3.0.0',
        processors: {
          'flutter:flavors': ProcessorLock(
            files: {
              'lib/main.dart': LockedFile(ownership: Ownership.scaffold),
              'lib/flavors.dart': LockedFile(
                ownership: Ownership.managed,
                hash: 'sha256:111',
              ),
            },
          ),
          'android:buildGradle': ProcessorLock(
            files: {
              'android/app/build.gradle': LockedFile(
                ownership: Ownership.patched,
                hash: 'sha256:222',
              ),
            },
          ),
        },
      );

      expect(
        LockCodec.encode(lock),
        contains(
          'processors:\n'
          '  android:buildGradle:\n'
          '    files:\n'
          '      android/app/build.gradle:\n'
          '        hash: sha256:222\n'
          '        ownership: patched\n'
          '  flutter:flavors:\n'
          '    files:\n'
          '      lib/flavors.dart:\n'
          '        hash: sha256:111\n'
          '        ownership: managed\n'
          '      lib/main.dart:\n'
          '        ownership: scaffold\n'
          'schemaVersion: 1\n',
        ),
      );
    });

    test('writes regions, owned keys, objects and inputs, sorted', () {
      final lock = FlavorizrLock(
        flavorizrVersion: '3.0.0',
        processors: {
          'p': ProcessorLock(
            regions: {
              'a.gradle': {'flavors': 'h2', 'dimensions': 'h1'},
            },
            keys: {
              'Info.plist': {'CFBundleName': 'h3'},
            },
            objects: {
              'project.pbxproj': {'ZZ99', 'AA11'},
            },
            inputs: {'assets/icon.png': 'h4'},
          ),
        },
      );

      expect(
        LockCodec.encode(lock),
        contains(
          '  p:\n'
          '    inputs:\n'
          '      assets/icon.png: h4\n'
          '    keys:\n'
          '      Info.plist:\n'
          '        CFBundleName: h3\n'
          '    objects:\n'
          '      project.pbxproj:\n'
          '        - AA11\n'
          '        - ZZ99\n'
          '    regions:\n'
          '      a.gradle:\n'
          '        dimensions: h1\n'
          '        flavors: h2\n',
        ),
      );
    });

    test('writes empty sections as empty flow mappings', () {
      expect(
        LockCodec.encode(FlavorizrLock(flavorizrVersion: '3.0.0')),
        contains('flavors: {}\n'),
      );
    });
  });

  group('LockCodec.decode', () {
    test('reads back what encode wrote', () {
      final lock = FlavorizrLock(
        flavorizrVersion: '3.0.0',
        flavors: {'prod': 'sha256:bbb', 'dev': 'sha256:aaa'},
      );

      expect(
        LockCodec.decode(LockCodec.encode(lock), runningVersion: '3.0.0'),
        lock,
      );
    });

    test('reads back the files of the processors', () {
      final lock = FlavorizrLock(
        flavorizrVersion: '3.0.0',
        flavors: {'dev': 'sha256:aaa'},
        processors: {
          'flutter:flavors': ProcessorLock(
            files: {
              'lib/main.dart': LockedFile(ownership: Ownership.scaffold),
              'lib/flavors.dart': LockedFile(
                ownership: Ownership.managed,
                hash: 'sha256:111',
              ),
            },
          ),
          'ios:plist': ProcessorLock(),
        },
      );

      expect(
        LockCodec.decode(LockCodec.encode(lock), runningVersion: '3.0.0'),
        lock,
      );
    });

    test('reads back regions, owned keys, objects and inputs', () {
      final lock = FlavorizrLock(
        flavorizrVersion: '3.0.0',
        processors: {
          'p': ProcessorLock(
            regions: {
              'a.gradle': {'flavors': 'h2', 'dimensions': 'h1'},
            },
            keys: {
              'Info.plist': {'CFBundleName': 'h3'},
            },
            objects: {
              'project.pbxproj': {'ZZ99', 'AA11'},
            },
            inputs: {'assets/icon.png': 'h4'},
          ),
        },
      );

      expect(
        LockCodec.decode(LockCodec.encode(lock), runningVersion: '3.0.0'),
        lock,
      );
    });

    test('reads back an empty lock', () {
      final lock = FlavorizrLock(flavorizrVersion: '3.0.0');

      expect(
        LockCodec.decode(LockCodec.encode(lock), runningVersion: '3.0.0'),
        lock,
      );
    });
  });

  group('determinism', () {
    FlavorizrLock build(List<String> order) => FlavorizrLock(
      flavorizrVersion: '3.0.0',
      flavors: {for (final name in order) name: 'hash-$name'},
      processors: {
        for (final id in order)
          id: ProcessorLock(
            files: {
              for (final path in order)
                path: LockedFile(ownership: Ownership.managed, hash: path),
            },
            regions: {
              for (final path in order) path: {for (final r in order) r: r},
            },
            objects: {
              'project.pbxproj': {...order},
            },
          ),
      },
    );

    test('does not depend on the order the content was built in', () {
      final forward = LockCodec.encode(build(['a', 'b', 'c']));
      final backward = LockCodec.encode(build(['c', 'b', 'a']));

      expect(backward, forward);
    });

    test('writes the same bytes again after a read', () {
      final text = LockCodec.encode(build(['b', 'a', 'c']));

      final again = LockCodec.encode(
        LockCodec.decode(text, runningVersion: '3.0.0'),
      );

      expect(again, text);
    });

    test('ends with a single newline, never uses CRLF or tabs', () {
      final text = LockCodec.encode(build(['b', 'a']));

      expect(text.endsWith('\n'), isTrue);
      expect(text.endsWith('\n\n'), isFalse);
      expect(text, isNot(contains('\r')));
      expect(text, isNot(contains('\t')));
    });

    test('keeps strings that look like other YAML types as strings', () {
      const tricky = [
        '',
        ' ',
        ' lead',
        'trail ',
        'true',
        'False',
        'null',
        '~',
        'yes',
        'no',
        'on',
        'off',
        '123',
        '-1',
        '1e3',
        '0x1F',
        '0o17',
        '.5',
        '.inf',
        '.NaN',
        '1.0',
        '3.0.0',
        'a: b',
        'a:',
        'a #b',
        '#a',
        '- a',
        '-',
        '? a',
        '[a]',
        '{a}',
        'a, b',
        '*a',
        '&a',
        '!a',
        '|a',
        '>a',
        '%a',
        '@a',
        '`a',
        "it's",
        'say "hi"',
        'back\\slash',
        'line\nbreak',
        'tab\there',
        'cr\rlf',
        'bell\u0007',
        'del\u007f',
        'nel\u0085',
        'ls\u2028ps\u2029',
        'caffè',
        '日本語',
        '🚀',
        'sha256:abc',
        'android:buildGradle',
        'lib/flavors.dart',
        '.idea/run.xml',
      ];

      final lock = FlavorizrLock(
        flavorizrVersion: '3.0.0',
        flavors: {for (final value in tricky) value: value},
        processors: {
          for (final value in tricky)
            value: ProcessorLock(
              keys: {
                value: {value: value},
              },
              objects: {
                value: {value},
              },
              inputs: {value: value},
            ),
        },
      );

      expect(
        LockCodec.decode(LockCodec.encode(lock), runningVersion: '3.0.0'),
        lock,
      );
    });
  });

  group('version guard', () {
    String lockText({int schema = 1, String version = '3.0.0'}) =>
        'flavorizrVersion: $version\n'
        'flavors: {}\n'
        'processors: {}\n'
        'schemaVersion: $schema\n';

    test('blocks a lock with a newer schema, with an upgrade hint', () {
      expect(
        () => LockCodec.decode(
          lockText(schema: 2, version: '3.2.0'),
          runningVersion: '3.0.0',
        ),
        throwsA(
          isA<UnsupportedLockVersionException>()
              .having((e) => e.lockVersion, 'lockVersion', '3.2.0')
              .having((e) => e.runningVersion, 'runningVersion', '3.0.0')
              .having(
                (e) => e.toString(),
                'message',
                allOf(
                  contains('3.2.0'),
                  contains('3.0.0'),
                  contains('Upgrade'),
                ),
              ),
        ),
      );
    });

    test('blocks a newer schema even if the rest has an unknown shape', () {
      expect(
        () => LockCodec.decode(
          'schemaVersion: 7\nsomething: [new, shape]\n',
          runningVersion: '3.0.0',
        ),
        throwsA(isA<UnsupportedLockVersionException>()),
      );
    });

    test('blocks a lock written by a newer flavorizr', () {
      for (final version in ['3.0.1', '3.1.0', '4.0.0', '3.0.10']) {
        expect(
          () => LockCodec.decode(
            lockText(version: version),
            runningVersion: '3.0.0',
          ),
          throwsA(isA<UnsupportedLockVersionException>()),
          reason: version,
        );
      }
    });

    test('blocks a release lock when running a pre-release of it', () {
      expect(
        () => LockCodec.decode(
          lockText(version: '3.0.0'),
          runningVersion: '3.0.0-beta.1',
        ),
        throwsA(isA<UnsupportedLockVersionException>()),
      );
      expect(
        () => LockCodec.decode(
          lockText(version: '3.0.0-beta.2'),
          runningVersion: '3.0.0-beta.1',
        ),
        throwsA(isA<UnsupportedLockVersionException>()),
      );
      expect(
        () => LockCodec.decode(
          lockText(version: '3.0.0-beta.10'),
          runningVersion: '3.0.0-beta.9',
        ),
        throwsA(isA<UnsupportedLockVersionException>()),
      );
    });

    test('accepts a lock written by the same or an older flavorizr', () {
      for (final version in [
        '3.0.0',
        '2.6.0',
        '3.0.0-beta.1',
        '2.99.99',
        '3.0.0+build.5',
      ]) {
        expect(
          LockCodec.decode(
            lockText(version: version),
            runningVersion: '3.0.0',
          ).flavorizrVersion,
          version,
          reason: version,
        );
      }

      expect(
        LockCodec.decode(
          lockText(version: '3.0.0-beta.1'),
          runningVersion: '3.0.0-beta.2',
        ),
        isA<FlavorizrLock>(),
      );
    });

    test('refuses a flavorizr version that is not a version', () {
      expect(
        () => LockCodec.decode(
          lockText(version: 'latest'),
          runningVersion: '3.0.0',
        ),
        throwsA(isA<MalformedLockFileException>()),
      );
    });
  });

  group('malformed input', () {
    void expectMalformed(String text) => expect(
      () => LockCodec.decode(text, runningVersion: '3.0.0'),
      throwsA(isA<MalformedLockFileException>()),
      reason: text,
    );

    test('is refused when it is not YAML or not a mapping', () {
      expectMalformed('a: [');
      expectMalformed('');
      expectMalformed('- a\n- b\n');
      expectMalformed('just text');
    });

    test('is refused without a valid schema version', () {
      expectMalformed('flavorizrVersion: 3.0.0\nflavors: {}\nprocessors: {}\n');
      expectMalformed(
        'schemaVersion: "1"\nflavorizrVersion: 3.0.0\n'
        'flavors: {}\nprocessors: {}\n',
      );
      expectMalformed(
        'schemaVersion: 0\nflavorizrVersion: 3.0.0\n'
        'flavors: {}\nprocessors: {}\n',
      );
    });

    test('is refused when a section has the wrong shape', () {
      const head = 'schemaVersion: 1\nflavorizrVersion: 3.0.0\n';

      expectMalformed('${head}flavors: x\nprocessors: {}\n');
      expectMalformed('${head}flavors: {dev: 1}\nprocessors: {}\n');
      expectMalformed('${head}flavors: {}\nprocessors: [a]\n');
      expectMalformed('${head}flavors: {}\nprocessors: {p: x}\n');
      expectMalformed('${head}flavors: {}\nprocessors: {p: {files: [a]}}\n');
      expectMalformed(
        '${head}flavors: {}\nprocessors: {p: {objects: {a: x}}}\n',
      );
      expectMalformed(
        '${head}flavors: {}\nprocessors: {p: {objects: {a: [1]}}}\n',
      );
    });

    test('is refused when a file entry is not valid', () {
      const head =
          'schemaVersion: 1\nflavorizrVersion: 3.0.0\nflavors: {}\n'
          'processors:\n  p:\n    files:\n      a.dart:\n';

      expectMalformed('$head        ownership: local\n');
      expectMalformed('$head        ownership: local\n        hash: h\n');
      expectMalformed('$head        ownership: managed\n');
      expectMalformed('$head        ownership: scaffold\n        hash: h\n');
      expectMalformed('$head        ownership: nobody\n        hash: h\n');
      expectMalformed('$head        hash: h\n');
    });
  });
}
