import 'dart:io';

import 'package:flutter_flavorizr/src/engine/adopt/legacy_artifacts.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

void main() {
  late Directory root;

  void write(String path, [String content = '']) =>
      File(p.join(root.path, path))
        ..parent.createSync(recursive: true)
        ..writeAsStringSync(content);

  List<String> found([Iterable<String> flavors = const ['dev']]) =>
      findLegacyArtifacts(root, flavors: flavors);

  setUp(() => root = Directory.systemTemp.createTempSync('flavorizr_legacy_'));
  tearDown(() => root.deleteSync(recursive: true));

  test('a project flavorizr never ran on has none', () {
    write('pubspec.yaml', 'name: app\n');
    write('android/app/build.gradle', 'android {}\n');
    write('ios/Runner.xcodeproj/project.pbxproj', 'name = Debug;\n');
    write('ios/Flutter/Debug.xcconfig', '');
    write('lib/main.dart', '');

    expect(found(), isEmpty);
  });

  test('knows the gradle file of flavorizr, and the marked blocks', () {
    write('android/app/flavorizr.gradle.kts');
    write(
      'android/app/build.gradle',
      '// ----- BEGIN flavorDimensions (autogenerated by flutter_flavorizr) '
          '-----\n',
    );

    expect(found(), [
      'android/app/build.gradle',
      'android/app/flavorizr.gradle.kts',
    ]);
  });

  test('knows the markers of the files of Linux and Windows', () {
    write(
      'linux/CMakeLists.txt',
      '# ----- BEGIN APPLICATION_ID (autogenerated by flutter_flavorizr) -----',
    );
    write(
      'windows/runner/CMakeLists.txt',
      '# ----- BEGIN x (autogenerated by flutter_flavorizr) -----',
    );

    expect(found(), ['linux/CMakeLists.txt', 'windows/runner/CMakeLists.txt']);
  });

  test('does not take for flavorizr\'s what a project flavorized by hand has: '
      'lib/flavors.dart, schemes, build configurations, app icon sets', () {
    write('lib/flavors.dart');
    write('ios/Runner.xcodeproj/xcshareddata/xcschemes/dev.xcscheme');
    write(
      'ios/Runner.xcodeproj/project.pbxproj',
      '\t\t\tname = "Debug-dev";\n',
    );
    write('ios/Runner/Assets.xcassets/AppIcon-dev.appiconset/Contents.json');

    expect(found(), isEmpty);
  });

  test('knows the xcconfigs of the flavors it is asked about, and the launch '
      'storyboard', () {
    write('ios/Flutter/devDebug.xcconfig');
    write('macos/Runner/Configs/devRelease.xcconfig');
    write('macos/Flutter/devProfile.xcconfig');
    write('ios/Runner/devLaunchScreen.storyboard');

    expect(found(), [
      'ios/Flutter/devDebug.xcconfig',
      'ios/Runner/devLaunchScreen.storyboard',
      'macos/Flutter/devProfile.xcconfig',
      'macos/Runner/Configs/devRelease.xcconfig',
    ]);
    expect(found(['other']), isEmpty);
  });

  test('does not follow a link, and ignores a name that is not a folder', () {
    final outside = Directory.systemTemp.createTempSync('flavorizr_outside_');

    addTearDown(() => outside.deleteSync(recursive: true));
    File(p.join(outside.path, 'flavors.dart')).writeAsStringSync('');
    Directory(p.join(root.path, 'lib')).createSync();
    Link(
      p.join(root.path, 'lib', 'flavors.dart'),
    ).createSync(p.join(outside.path, 'flavors.dart'));
    write('ios/Flutter/DebugDebug.xcconfig');

    expect(found(['../x', '', 'a/b', '.']), isEmpty);
  });
}
