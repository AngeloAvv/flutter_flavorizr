import 'package:flutter_flavorizr/src/engine/processors/android/android_build_gradle_editor.dart';
import 'package:flutter_flavorizr/src/exception/existing_flavor_dimensions_exception.dart';
import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';
import 'package:flutter_test/flutter_test.dart';

const _begin =
    '// ----- BEGIN flavorDimensions (autogenerated by flutter_flavorizr) -----';
const _end =
    '// ----- END flavorDimensions (autogenerated by flutter_flavorizr) -----';

const _groovyApply = 'apply from: "flavorizr.gradle"';
const _kotlinApply = 'apply { from("flavorizr.gradle.kts") }';

const _groovyRegion = '$_begin\n$_groovyApply\n$_end';
const _kotlinRegion = '$_begin\n$_kotlinApply\n$_end';

const _base = '''
plugins {
    id "com.android.application"
}

android {
    namespace "com.example.app"
}
''';

String _edit(String source, [BuildGradleDsl dsl = BuildGradleDsl.groovy]) =>
    AndroidBuildGradleEditor.withFlavorizrRegion(source, dsl);

void main() {
  group('AndroidBuildGradleEditor.withFlavorizrRegion', () {
    test('appends the region to a build file that has none, Groovy', () {
      expect(_edit(_base), '$_base$_groovyRegion');
    });

    test('appends the region to a build file that has none, Kotlin', () {
      expect(_edit(_base, BuildGradleDsl.kotlin), '$_base$_kotlinRegion');
    });

    test('adds the missing line break before the region', () {
      expect(_edit(_base.trimRight()), '${_base.trimRight()}\n$_groovyRegion');
    });

    test('writes the region with the line endings of the file', () {
      final crlf = _base.replaceAll('\n', '\r\n');

      expect(_edit(crlf), '$crlf${_groovyRegion.replaceAll('\n', '\r\n')}');
    });

    test('leaves a build file with an up to date region as it is', () {
      final source = '$_base$_groovyRegion';

      expect(_edit(source), source);
    });

    test('finds an up to date region wherever it is and however indented, '
        'with any line ending', () {
      final source =
          'android {\r\n  $_begin\r\n  $_groovyApply  \r\n\t$_end\r\n}\r\n';

      expect(_edit(source), source);
    });

    test('is idempotent', () {
      final once = _edit(_base);

      expect(_edit(once), once);
    });

    test('replaces a region that is not up to date and moves it to the end, '
        'like 2.x', () {
      const old =
          '''
android {
    $_begin
    flavorDimensions += "flavor-type"
    $_end

    compileSdk 34
}
''';

      expect(_edit(old), 'android {\n\n    compileSdk 34\n}\n$_groovyRegion');
    });

    test(
      'changes the DSL of the region when it is not the one of the file',
      () {
        expect(
          _edit('$_base$_groovyRegion\n', BuildGradleDsl.kotlin),
          '$_base$_kotlinRegion',
        );
      },
    );

    test('collapses duplicated regions into one', () {
      expect(
        _edit('$_base$_groovyRegion\n\n$_groovyRegion\n'),
        '$_base\n$_groovyRegion',
      );
    });

    test('keeps everything outside the region byte for byte', () {
      const source =
          '// head\n\tweird   spacing \r\nandroid {\n}\n\n\n// tail with no eol';

      final edited = _edit(source);

      expect(edited, startsWith('$source\n'));
      expect(edited, endsWith(_groovyRegion));
    });

    group('adopts the unmarked line of a 2.x run in place', () {
      test('Groovy, keeping its indentation', () {
        expect(
          _edit('android {\n}\n  $_groovyApply\nfoo()\n'),
          'android {\n}\n  $_begin\n  $_groovyApply\n  $_end\nfoo()\n',
        );
      });

      test('Groovy, with single quotes and a semicolon', () {
        expect(
          _edit("android {\n}\napply from: 'flavorizr.gradle';\n"),
          'android {\n}\n$_groovyRegion\n',
        );
      });

      test('Kotlin', () {
        expect(
          _edit('android {\n}\n$_kotlinApply\n', BuildGradleDsl.kotlin),
          'android {\n}\n$_kotlinRegion\n',
        );
      });

      test('Kotlin, in the call form', () {
        expect(
          _edit(
            'android {\n}\napply(from = "flavorizr.gradle.kts")\n',
            BuildGradleDsl.kotlin,
          ),
          'android {\n}\n$_kotlinRegion\n',
        );
      });

      test('only the first one, the others are the user\'s', () {
        expect(
          _edit('android {\n}\n$_groovyApply\n$_groovyApply\n'),
          'android {\n}\n$_groovyRegion\n$_groovyApply\n',
        );
      });

      test('not when it is commented out, and the region is appended', () {
        const source = 'android {\n}\n// $_groovyApply\n';

        expect(_edit(source), '$source$_groovyRegion');
      });

      test('not when it applies another file', () {
        const source = 'android {\n}\napply from: "other.gradle"\n';

        expect(_edit(source), '$source$_groovyRegion');
      });

      test('not the Groovy line of a Kotlin project', () {
        const source = 'android {\n}\n$_groovyApply\n';

        expect(_edit(source, BuildGradleDsl.kotlin), '$source$_kotlinRegion');
      });
    });

    group('refuses to touch a build file', () {
      test('without the android block', () {
        expect(
          () => _edit('plugins {}\n'),
          throwsA(isA<MalformedResourceException>()),
        );
        expect(() => _edit(''), throwsA(isA<MalformedResourceException>()));
      });

      test('that has flavor dimensions of the user', () {
        expect(
          () => _edit('android {\n  flavorDimensions "mine"\n}\n'),
          throwsA(isA<ExistingFlavorDimensionsException>()),
        );
      });

      for (final (name, source) in [
        ('a begin marker without end', 'android {\n}\n$_begin\n'),
        ('an end marker without begin', 'android {\n}\n$_end\n'),
        ('an end marker before the begin', 'android {\n}\n$_end\n$_begin\n'),
        (
          'a begin marker inside a region',
          'android {\n}\n$_begin\n$_begin\n$_end\n',
        ),
      ]) {
        test('with $name', () {
          expect(
            () => _edit(source),
            throwsA(isA<ExistingFlavorDimensionsException>()),
          );
        });
      }
    });
  });

  group('AndroidBuildGradleEditor.ownedContent', () {
    test('is the region of the file, nothing when there is none', () {
      expect(AndroidBuildGradleEditor.ownedContent(_base), isEmpty);
      expect(
        AndroidBuildGradleEditor.ownedContent('$_base$_groovyRegion'),
        _groovyRegion,
      );
    });

    test('ignores everything outside the region, indentation and line '
        'endings', () {
      final base = AndroidBuildGradleEditor.ownedContent(
        '$_base$_groovyRegion',
      );

      expect(
        AndroidBuildGradleEditor.ownedContent(
          '// edited\r\n${_base.replaceAll('\n', '\r\n')}\r\n  '
          '${_groovyRegion.replaceAll('\n', '\r\n  ')}\r\n// more',
        ),
        base,
      );
    });

    test('changes when the region is edited', () {
      expect(
        AndroidBuildGradleEditor.ownedContent(
          '$_base$_begin\napply from: "mine.gradle"\n$_end',
        ),
        isNot(AndroidBuildGradleEditor.ownedContent('$_base$_groovyRegion')),
      );
    });
  });
}
