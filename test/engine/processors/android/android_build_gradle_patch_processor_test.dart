import 'dart:convert';
import 'dart:io';

import 'package:flutter_flavorizr/src/engine/artifact.dart';
import 'package:flutter_flavorizr/src/engine/execution_plan.dart';
import 'package:flutter_flavorizr/src/engine/flavorizr_context.dart';
import 'package:flutter_flavorizr/src/engine/processors/android/android_build_gradle_patch_processor.dart';
import 'package:flutter_flavorizr/src/engine/processors/android/flavorizr_gradle_processor.dart';
import 'package:flutter_flavorizr/src/exception/existing_flavor_dimensions_exception.dart';
import 'package:flutter_flavorizr/src/exception/file_not_found_exception.dart';
import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';
import 'package:test/test.dart';
import 'package:path/path.dart' as p;

import '../../../test_utils.dart';

const _begin =
    '// ----- BEGIN flavorDimensions (autogenerated by flutter_flavorizr) -----';
const _end =
    '// ----- END flavorDimensions (autogenerated by flutter_flavorizr) -----';

const _build = 'plugins {\n  id "com.android.application"\n}\n\nandroid {\n}\n';

void main() {
  late Directory root;
  late Directory projectRoot;
  late FlavorizrContext ctx;

  File file(Directory base, String path) => File(p.join(base.path, path));

  setUp(() {
    final temp = Directory.systemTemp.createTempSync('flavorizr_build_');
    addTearDown(() => temp.deleteSync(recursive: true));

    root = Directory(p.join(temp.path, 'shadow'))..createSync();
    projectRoot = Directory(p.join(temp.path, 'project'))..createSync();

    ctx = FlavorizrContext(
      config: TestUtils.parseFlavorizr('test_resources/pubspec'),
      root: root,
      projectRoot: projectRoot,
      logger: TestUtils.quietLogger(),
    );
  });

  group('AndroidBuildGradlePatchProcessor', () {
    test('is the `android:buildGradle` processor, which needs the flavors '
        'file', () {
      final processor = AndroidBuildGradlePatchProcessor();

      expect(processor.id, 'android:buildGradle');
      expect(processor.dependsOn, {const FlavorizrGradleProcessor().id});
      expect(processor.after, isEmpty);
      expect(processor.requires, isEmpty);
    });

    test('pulls the flavors processor in the plan and runs it first', () {
      final plan = resolveExecutionPlan(
        [AndroidBuildGradlePatchProcessor(), const FlavorizrGradleProcessor()],
        requested: ['android:buildGradle'],
      );

      expect(plan.steps.map((step) => step.processor.id), [
        'android:flavorizrGradle',
        'android:buildGradle',
      ]);
    });

    for (final (build, flavors, apply) in [
      ('build.gradle', 'flavorizr.gradle', 'apply from: "flavorizr.gradle"'),
      (
        'build.gradle.kts',
        'flavorizr.gradle.kts',
        'apply { from("flavorizr.gradle.kts") }',
      ),
    ]) {
      group('on $build', () {
        final path = 'android/app/$build';

        test('adds the region that applies $flavors and tracks the build '
            'file as patched', () async {
          file(root, path)
            ..createSync(recursive: true)
            ..writeAsStringSync(_build);

          await AndroidBuildGradlePatchProcessor().apply(ctx);

          expect(
            file(root, path).readAsStringSync(),
            '$_build$_begin\n$apply\n$_end',
          );
          expect(ctx.tracked, [Artifact.patched(path)]);
        });

        test('reads the shadow workspace, never the real project nor the '
            'working directory', () async {
          file(root, path)
            ..createSync(recursive: true)
            ..writeAsStringSync(_build);
          file(projectRoot, path)
            ..createSync(recursive: true)
            ..writeAsStringSync('// real\nandroid {\n}\n');

          await AndroidBuildGradlePatchProcessor().apply(ctx);

          expect(
            file(projectRoot, path).readAsStringSync(),
            '// real\nandroid {\n}\n',
          );
          expect(File(path).existsSync(), isFalse);
        });

        test(
          'does not write a build file that is already up to date',
          () async {
            final target = file(root, path)..createSync(recursive: true);
            target.writeAsStringSync('$_build$_begin\n$apply\n$_end\n');
            final modified = DateTime.utc(2020);
            target.setLastModifiedSync(modified);

            await AndroidBuildGradlePatchProcessor().apply(ctx);

            expect(target.lastModifiedSync().toUtc(), modified);
            expect(ctx.tracked, [Artifact.patched(path)]);
          },
        );
      });
    }

    test(
      'keeps the byte order mark and the line endings of the file',
      () async {
        final target = file(root, 'android/app/build.gradle')
          ..createSync(recursive: true);
        target.writeAsBytesSync([
          0xef,
          0xbb,
          0xbf,
          ...utf8.encode('// é\r\nandroid {\r\n}\r\n'),
        ]);

        await AndroidBuildGradlePatchProcessor().apply(ctx);

        expect(target.readAsBytesSync(), [
          0xef,
          0xbb,
          0xbf,
          ...utf8.encode(
            '// é\r\nandroid {\r\n}\r\n$_begin\r\n'
            'apply from: "flavorizr.gradle"\r\n$_end',
          ),
        ]);
      },
    );

    test('follows the DSL like 2.x: Groovy wins when both build files '
        'exist', () async {
      for (final path in ['build.gradle', 'build.gradle.kts']) {
        file(root, 'android/app/$path')
          ..createSync(recursive: true)
          ..writeAsStringSync(_build);
      }

      await AndroidBuildGradlePatchProcessor().apply(ctx);

      expect(
        file(root, 'android/app/build.gradle').readAsStringSync(),
        contains('apply from: "flavorizr.gradle"'),
      );
      expect(
        file(root, 'android/app/build.gradle.kts').readAsStringSync(),
        _build,
      );
      expect(ctx.tracked, [Artifact.patched('android/app/build.gradle')]);
    });

    test('fails when there is no build file', () {
      expect(
        AndroidBuildGradlePatchProcessor().apply(ctx),
        throwsA(isA<FileNotFoundException>()),
      );
      expect(ctx.tracked, isEmpty);
    });

    test('fails on a build file without the android block', () {
      file(root, 'android/app/build.gradle')
        ..createSync(recursive: true)
        ..writeAsStringSync('plugins {}\n');

      expect(
        AndroidBuildGradlePatchProcessor().apply(ctx),
        throwsA(isA<MalformedResourceException>()),
      );
    });

    test('fails, and writes nothing, on a build file with flavor dimensions '
        'of the user', () async {
      final target = file(root, 'android/app/build.gradle')
        ..createSync(recursive: true);
      const source = 'android {\n  flavorDimensions "mine"\n}\n';
      target.writeAsStringSync(source);

      await expectLater(
        AndroidBuildGradlePatchProcessor().apply(ctx),
        throwsA(isA<ExistingFlavorDimensionsException>()),
      );
      expect(target.readAsStringSync(), source);
    });
  });
}
