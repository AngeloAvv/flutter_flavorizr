import 'dart:io';

import 'package:flutter_flavorizr/src/engine/processors/windows/windows_runner_cmake_lists_editor.dart';
import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';
import 'package:flutter_flavorizr/src/exception/unsupported_runner_layout_exception.dart';
import 'package:flutter_test/flutter_test.dart';

const _titles = {'apple': 'Apple App', 'banana': 'Banana App'};

const _begin =
    '# ----- BEGIN FLUTTER_APP_FLAVOR (autogenerated by flutter_flavorizr) -----';
const _end =
    '# ----- END FLUTTER_APP_FLAVOR (autogenerated by flutter_flavorizr) -----';

/// What the region is for [titles].
String _region(Map<String, String> titles) {
  final entries = titles.entries.toList();

  return [
    _begin,
    'set(RUNNER_APP_ICON "app_icon.ico")',
    r'set(WINDOW_TITLE_CPP "${BINARY_NAME}")',
    r'set(WINDOW_TITLE_RC "${BINARY_NAME}")',
    'if(DEFINED FLUTTER_APP_FLAVOR)',
    for (final (index, entry) in entries.indexed) ...[
      '  ${index == 0 ? 'if' : 'elseif'}(FLUTTER_APP_FLAVOR STREQUAL "${entry.key}")',
      '    set(RUNNER_APP_ICON "${entry.key}.ico")',
      '    set(WINDOW_TITLE_CPP "${entry.value}")',
      '    set(WINDOW_TITLE_RC "${entry.value}")',
    ],
    '  endif()',
    'endif()',
    '',
    r'set(WINDOW_TITLE "${WINDOW_TITLE_RC}")',
    'configure_file(',
    r'  "${CMAKE_CURRENT_SOURCE_DIR}/Runner.rc.in"',
    r'  "${CMAKE_CURRENT_BINARY_DIR}/Runner.rc"',
    '  @ONLY',
    ')',
    r'set(WINDOW_TITLE "${WINDOW_TITLE_CPP}")',
    'configure_file(',
    r'  "${CMAKE_CURRENT_SOURCE_DIR}/main.cpp.in"',
    r'  "${CMAKE_CURRENT_BINARY_DIR}/main.cpp"',
    '  @ONLY',
    ')',
    r'get_target_property(FLAVORIZR_RUNNER_SOURCES ${BINARY_NAME} SOURCES)',
    'list(REMOVE_ITEM FLAVORIZR_RUNNER_SOURCES',
    '  "main.cpp"',
    r'  "${CMAKE_CURRENT_SOURCE_DIR}/main.cpp"',
    '  "Runner.rc"',
    r'  "${CMAKE_CURRENT_SOURCE_DIR}/Runner.rc"',
    ')',
    r'set_property(TARGET ${BINARY_NAME} PROPERTY SOURCES ${FLAVORIZR_RUNNER_SOURCES})',
    r'target_sources(${BINARY_NAME} PRIVATE',
    r'  "${CMAKE_CURRENT_BINARY_DIR}/main.cpp"',
    r'  "${CMAKE_CURRENT_BINARY_DIR}/Runner.rc"',
    ')',
    r'target_include_directories(${BINARY_NAME} PRIVATE "${CMAKE_CURRENT_SOURCE_DIR}")',
    _end,
  ].join('\n');
}

const _call =
    r'add_executable(${BINARY_NAME} WIN32'
    '\n'
    '  "flutter_window.cpp"\n'
    '  "main.cpp"\n'
    '  "Runner.rc"\n'
    ')';

String _pristine([String call = _call]) =>
    'cmake_minimum_required(VERSION 3.14)\n'
    'project(runner LANGUAGES CXX)\n'
    '\n'
    '# Any new source files that you add to the application should be added '
    'here.\n'
    '$call\n'
    '\n'
    r'apply_standard_settings(${BINARY_NAME})'
    '\n';

String _edit(String source, [Map<String, String> titles = _titles]) =>
    WindowsRunnerCMakeListsEditor.withFlavors(source, titles);

String _read(String path) => File(path).readAsStringSync();

const _resources = 'test_resources/windows/runner_cmake_lists_processor_test';

/// A source the editor cannot edit, and why it does not.
typedef _Rejected = ({String name, String source, Pattern message});

void main() {
  group('WindowsRunnerCMakeListsEditor', () {
    test('adds the region right after the call that adds the executable, '
        'which is the only thing it changes', () {
      expect(
        _edit(_pristine()),
        _pristine(
          _call,
        ).replaceFirst('$_call\n', '$_call\n${_region(_titles)}\n'),
      );
    });

    test('sends the configure_file outputs to the binary dir and none to '
        'the source dir', () {
      final patched = _edit(_pristine());
      final region = patched.substring(
        patched.indexOf(_begin),
        patched.indexOf(_end),
      );

      expect(
        RegExp(
          r'configure_file\(\s*"([^"]*)"\s*"([^"]*)"',
        ).allMatches(region).map((match) => match.group(2)),
        [
          r'${CMAKE_CURRENT_BINARY_DIR}/Runner.rc',
          r'${CMAKE_CURRENT_BINARY_DIR}/main.cpp',
        ],
      );
      expect(
        region,
        isNot(
          contains(
            r'"${CMAKE_CURRENT_SOURCE_DIR}/main.cpp"'
            '\n  @ONLY',
          ),
        ),
      );
    });

    test('regenerates the region of the pristine file of Flutter, with the '
        'real template untouched outside of it', () {
      final source = _read('$_resources/CMakeLists.txt');
      final patched = _edit(source);

      expect(patched, contains(_region(_titles)));
      expect(patched.replaceFirst('${_region(_titles)}\n', ''), source);
    });

    test('is up to date after one run', () {
      final once = _edit(_pristine());

      expect(_edit(once), once);
    });

    test('regenerates the region without the flavor that was removed, in '
        'place and with nothing else touched', () {
      final first = _edit(_pristine());
      final second = _edit(first, {'apple': 'Apple App'});

      expect(second, isNot(contains('banana')));
      expect(
        second,
        _pristine().replaceFirst(
          '$_call\n',
          '$_call\n${_region({'apple': 'Apple App'})}\n',
        ),
      );
    });

    test('keeps the region where the user put it, as long as it is after '
        'the call', () {
      final moved = _pristine().replaceFirst(
        '\napply_standard_settings',
        '\n# mine\n${_region({'apple': 'Old'})}\n# mine too\napply_standard_settings',
      );

      expect(
        _edit(moved),
        _pristine().replaceFirst(
          '\napply_standard_settings',
          '\n# mine\n${_region(_titles)}\n# mine too\napply_standard_settings',
        ),
      );
    });

    group('a project flavorized by 2.x', () {
      final twoX = _read('$_resources/CMakeLists_expected.txt');

      test('has its region, which sat before the call, moved after it: '
          'nothing else changes, but the blank line 2.x left', () {
        final patched = _edit(twoX);
        final region = _region(_titles);

        expect(patched.indexOf(_begin), greaterThan(patched.indexOf(')\n')));
        expect(
          patched.indexOf(_begin),
          greaterThan(patched.indexOf(r'add_executable(${BINARY_NAME} WIN32')),
        );
        expect(
          patched.replaceFirst('$region\n', ''),
          twoX.replaceFirst(
            RegExp(
              '${RegExp.escape(_begin)}.*?${RegExp.escape(_end)}\n',
              dotAll: true,
            ),
            '',
          ),
        );
        expect(_edit(patched), patched);
      });

      test('is not left with the configure_file calls of 2.x, which write '
          'into the source dir', () {
        final patched = _edit(twoX);

        expect(
          patched,
          isNot(
            contains(
              r'"${CMAKE_CURRENT_SOURCE_DIR}/Runner.rc"'
              '\n  @ONLY',
            ),
          ),
        );
      });
    });

    test('keeps the line endings of the file', () {
      final patched = _edit(_pristine().replaceAll('\n', '\r\n'));

      expect(patched.replaceAll('\r\n', ''), isNot(contains('\n')));
      expect(patched, contains(_begin));
      expect(_edit(patched), patched);
    });

    test('accepts a call that ends the file, and does not add a line '
        'break the file did not have', () {
      const source = 'project(x)\n$_call';
      final patched = _edit(source);

      expect(patched, '$source\n${_region(_titles)}');
      expect(_edit(patched), patched);
    });

    test('skips the comments among the sources, whatever they end with', () {
      final source = _pristine(
        'add_executable(\${BINARY_NAME} WIN32\n'
        '  # the sources\n'
        '  "main.cpp"\n'
        '  "Runner.rc"\n'
        ')',
      );

      expect(_edit(source), contains(_region(_titles)));
    });

    test('moves a region that is inside the call, or that there are two of, '
        'after the call', () {
      final inside = _pristine(
        'add_executable(\${BINARY_NAME} WIN32\n'
        '${_region({'apple': 'Old'})}\n'
        '  "main.cpp"\n'
        '  "Runner.rc"\n'
        ')',
      );
      final two = _pristine().replaceFirst(
        '\nproject(',
        '\n${_region({'apple': 'Old'})}\nproject(',
      );

      for (final source in [inside, two]) {
        final patched = _edit(source);

        expect(_begin.allMatches(patched), hasLength(1));
        expect(patched.indexOf(_begin), greaterThan(patched.indexOf('\n)\n')));
        expect(_edit(patched), patched);
      }
    });

    test('indents the region like the line that closes the call', () {
      final source =
          'if(WIN32)\n'
          '  add_executable(\${BINARY_NAME} WIN32\n'
          '    "main.cpp"\n'
          '    "Runner.rc"\n'
          '  )\n'
          'endif()\n';
      final patched = _edit(source);

      expect(patched, contains('\n  $_begin\n'));
      expect(patched, contains('\n  $_end\n'));
      expect(_edit(patched), patched);
    });

    test('ignores a marker that is only part of a line', () {
      final source = '# see $_begin for more\n${_pristine()}';

      expect(_edit(source), contains('${_region(_titles)}\n'));
    });

    test('accepts the sources in the other ways it recognises', () {
      final call = _pristine(
        'add_executable(\${BINARY_NAME} WIN32\n'
        '  main.cpp\n'
        '  "\${CMAKE_CURRENT_SOURCE_DIR}/Runner.rc"\n'
        ')',
      );

      expect(_edit(call), contains(_region(_titles)));
    });

    test('removes every spelling it accepts from the target, and only those: '
        'the unrelated sources, whatever they are called, are left alone', () {
      const call =
          'add_executable(\${BINARY_NAME} WIN32\n'
          '  "flutter_window.cpp"\n'
          '  "domain.cpp"\n'
          '  "my_main.cpp"\n'
          '  "main.cpp.in"\n'
          '  "Runner.rc.in"\n'
          '  "main.cpp"\n'
          '  \${CMAKE_CURRENT_SOURCE_DIR}/Runner.rc\n'
          ')';
      final patched = _edit(_pristine(call));
      final removed = RegExp(r'list\(REMOVE_ITEM[^)]*\)')
          .firstMatch(patched)!
          .group(0)!
          .split('\n')
          .map((line) => line.trim())
          .where((line) => line.startsWith('"'))
          .toSet();

      expect(removed, {
        for (final name in ['main.cpp', 'Runner.rc'])
          for (final spelling in WindowsRunnerCMakeListsEditor.sourceSpellings(
            name,
          ))
            '"$spelling"',
      });
      expect(patched, contains(call));
    });

    test('accepts every spelling it removes, quoted or not', () {
      for (final main in WindowsRunnerCMakeListsEditor.sourceSpellings(
        'main.cpp',
      )) {
        for (final rc in WindowsRunnerCMakeListsEditor.sourceSpellings(
          'Runner.rc',
        )) {
          for (final quote in ['', '"']) {
            final call = _pristine(
              'add_executable(\${BINARY_NAME} WIN32\n'
              '  $quote$main$quote\n  $quote$rc$quote\n)',
            );

            expect(_edit(call), contains(_begin), reason: '$main $rc $quote');
          }
        }
      }
    });

    test('accepts later calls that add other sources', () {
      for (final later in [
        'target_sources(\${BINARY_NAME} PRIVATE "extra.cpp" "domain.cpp")',
        'target_sources(\${BINARY_NAME} PRIVATE\n  "extra.cpp"\n)',
        'set(A "x # y")',
        'set(A "a \\" b")',
        'set(A "two\nlines")',
      ]) {
        final source = _pristine().replaceFirst(
          '\napply_standard_settings',
          '\n$later\napply_standard_settings',
        );
        final patched = _edit(source);

        expect(patched, contains(_begin), reason: later);
        expect(patched, contains('\n$later\n'), reason: later);
      }
    });

    group('writes the title the way each file it ends up in reads it', () {
      /// What CMake makes of the argument of `set(VAR "...")`.
      String cmakeValue(String argument) =>
          argument.replaceAllMapped(RegExp(r'\\(.)'), (match) => match[1]!);

      /// The values the region gives `WINDOW_TITLE_CPP` and `WINDOW_TITLE_RC`
      /// for the only flavor, after CMake decoded them, put where
      /// `configure_file` puts them in the templates.
      ({String main, String rc}) generated(String title) {
        final region = _edit(_pristine(), {'apple': title});
        String value(String name) => cmakeValue(
          RegExp(
            'set\\($name "((?:[^"\\\\]|\\\\.)*)"\\)',
          ).allMatches(region).last.group(1)!,
        );

        return (
          main: _read(
            'test_resources/windows/main_cpp_title_processor_test/main_expected.cpp',
          ).replaceAll('@WINDOW_TITLE@', value('WINDOW_TITLE_CPP')),
          rc: _read(
            'test_resources/windows/runner_rc_content_processor_test/Runner_expected.rc',
          ).replaceAll('@WINDOW_TITLE@', value('WINDOW_TITLE_RC')),
        );
      }

      // The title, what main.cpp holds for it, and what Runner.rc holds.
      final titles = [
        ('Apple App', 'Apple App', 'Apple App'),
        (r'My "App"', r'My \"App\"', 'My ""App""'),
        (r'a\b', r'a\\b', r'a\\b'),
        (
          r'ends with a backslash\',
          r'ends with a backslash\\',
          r'ends with a backslash\\',
        ),
        (
          r'${HOME} $x @VAR@ a;b [c] 100%',
          r'${HOME} $x @VAR@ a;b [c] 100%',
          r'${HOME} $x @VAR@ a;b [c] 100%',
        ),
        ('Café 😀', r'Caf\u00e9 \U0001f600', 'Café 😀'),
      ];

      for (final (title, cpp, rc) in titles) {
        test('`$title`', () {
          final files = generated(title);

          expect(files.main, contains('window.Create(L"$cpp", origin, size)'));
          expect(files.rc, contains('VALUE "FileDescription", "$rc" "\\0"'));
          expect(files.rc, contains('VALUE "ProductName", "$rc" "\\0"'));
        });
      }

      test('rejects a title with a line break or a control character', () {
        for (final title in ['a\nb', 'a\tb', 'a\u0000b', 'a\u0085b']) {
          expect(
            () => _edit(_pristine(), {'apple': title}),
            throwsA(
              isA<UnsupportedRunnerLayoutException>().having(
                (e) => e.toString(),
                'message',
                allOf(contains('apple'), contains('control')),
              ),
            ),
            reason: title.codeUnits.toString(),
          );
        }
      });

      test('rejects a flavor name that is not a plain name, since it is the '
          'name of an icon file and goes into CMake and Runner.rc', () {
        for (final name in ['a"b', r'a\b', 'a/b', r'a$b', 'a b', 'a;b', '']) {
          expect(
            () => _edit(_pristine(), {name: 'Title'}),
            throwsA(isA<UnsupportedRunnerLayoutException>()),
            reason: name,
          );
        }
        expect(
          _edit(_pristine(), {'my-flavor_2.x': 'Title'}),
          contains(_begin),
        );
      });

      test('rejects a flavor name that Windows reserves, with or without an '
          'extension and in any case, and one that ends with a dot', () {
        for (final name in [
          'CON',
          'con',
          'Prn',
          'AUX',
          'nul',
          'NUL',
          'com1',
          'COM9',
          'lpt1',
          'LPT9',
          'con.x',
          'Nul.v2',
          'aux.',
          'apple.',
        ]) {
          expect(
            () => _edit(_pristine(), {name: 'Title'}),
            throwsA(
              isA<UnsupportedRunnerLayoutException>().having(
                (e) => e.toString(),
                'message',
                contains(name),
              ),
            ),
            reason: name,
          );
        }

        for (final name in [
          'com0',
          'com10',
          'lpt0',
          'console',
          'auxiliary',
          'con-x',
          'nu',
          'a.con',
        ]) {
          expect(
            _edit(_pristine(), {name: 'Title'}),
            contains(_begin),
            reason: name,
          );
        }
      });
    });

    test('builds with the defaults, and not with an empty icon, when the '
        'flavor is not one of the configured ones', () {
      final region = _edit(_pristine());
      final defaults = region.indexOf('set(RUNNER_APP_ICON "app_icon.ico")');

      expect(defaults, greaterThan(region.indexOf(_begin)));
      expect(
        defaults,
        lessThan(region.indexOf('if(DEFINED FLUTTER_APP_FLAVOR)')),
      );
      expect(region, isNot(contains('else()')));
    });

    group('rejects what it cannot edit with an actionable error', () {
      final cases = <_Rejected>[
        (
          name: 'a quoted [[ is a mention of a bracket',
          source: 'set(A "[[")\n${_pristine()}',
          message: 'bracket',
        ),
        (
          name: 'a [[ in a comment is a mention of a bracket',
          source: '# see [[x\n${_pristine()}',
          message: 'bracket',
        ),
        (
          name: 'a later call has an escaped parenthesis before main.cpp',
          source: _pristine().replaceFirst(
            '\napply_standard_settings',
            '\ntarget_sources(\${BINARY_NAME} PRIVATE\n  custom\\).cpp\n'
                '  "main.cpp"\n)\napply_standard_settings',
          ),
          message: 'main.cpp',
        ),
        (
          name: 'a comment among the sources has a parenthesis',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32\n  # the sources (all)\n'
            '  "main.cpp"\n  "Runner.rc"\n)',
          ),
          message: 'closing',
        ),
        (
          name: 'the file has a bracket comment',
          source: '#[[ a comment\n)\n]]\n${_pristine()}',
          message: 'bracket',
        ),
        (
          name: 'the file has a bracket comment with an equals sign',
          source: '#[==[ a ]] comment ]==]\n${_pristine()}',
          message: 'bracket',
        ),
        (
          name: 'the file has a bracket argument',
          source: 'message([[text]])\n${_pristine()}',
          message: 'bracket',
        ),
        (
          name: 'a later call has a bracket comment with a parenthesis',
          source: _pristine().replaceFirst(
            '\napply_standard_settings',
            '\ntarget_sources(\${BINARY_NAME} PRIVATE\n  #[[\n  )\n  ]]\n  "main.cpp"\n)\napply_standard_settings',
          ),
          message: 'bracket',
        ),
        (
          name: 'a line of the file ends with a backslash',
          source: 'set(A "x\\\n y")\n${_pristine()}',
          message: 'continuation',
        ),
        (
          name: 'a quoted argument over several lines holds the call',
          source:
              'set(A "x\nadd_executable(\${BINARY_NAME} WIN32\ny")\n${_pristine()}',
          message: 'more than one',
        ),
        (
          name: 'a comment that ends with a backslash',
          source: '# a comment \\\n${_pristine()}',
          message: 'continuation',
        ),
        (
          name: 'the call is only in a comment',
          source: '# add_executable(\${BINARY_NAME} WIN32\n${_pristine()}',
          message: 'add_executable',
        ),
        (
          name: 'another target is added, with main.cpp',
          source: '${_pristine()}add_executable(other "main.cpp")\n',
          message: 'add_executable',
        ),
        (
          name: 'a later target_sources is commented out, and names main.cpp',
          source: _pristine().replaceFirst(
            '\napply_standard_settings',
            '\n# target_sources(\${BINARY_NAME} PRIVATE "main.cpp")\napply_standard_settings',
          ),
          message: 'main.cpp',
        ),
        (
          name: 'a comment among the sources names Runner.rc',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32\n  "main.cpp"\n  # was ./Runner.rc\n  "Runner.rc"\n)',
          ),
          message: 'Runner.rc',
        ),
        (
          name: 'a later target_sources adds main.cpp',
          source: _pristine().replaceFirst(
            '\napply_standard_settings',
            '\ntarget_sources(\${BINARY_NAME} PRIVATE "main.cpp")\napply_standard_settings',
          ),
          message: 'main.cpp',
        ),
        (
          name: 'a later multi-line target_sources adds an alias of Runner.rc',
          source: _pristine().replaceFirst(
            '\napply_standard_settings',
            '\ntarget_sources(\${BINARY_NAME} PRIVATE\n  "extra.cpp"\n  "./Runner.rc"\n)\napply_standard_settings',
          ),
          message: 'Runner.rc',
        ),
        (
          name: 'a later TARGET_SOURCES is in upper case',
          source: _pristine().replaceFirst(
            '\napply_standard_settings',
            '\nTARGET_SOURCES(runner PRIVATE main.cpp)\napply_standard_settings',
          ),
          message: 'main.cpp',
        ),
        (
          name: 'a later set_property appends main.cpp to the sources',
          source: _pristine().replaceFirst(
            '\napply_standard_settings',
            '\nset_property(TARGET \${BINARY_NAME} APPEND PROPERTY SOURCES\n  "\${CMAKE_CURRENT_SOURCE_DIR}/main.cpp")\napply_standard_settings',
          ),
          message: 'main.cpp',
        ),
        (
          name: 'a later set_target_properties sets the sources',
          source: _pristine().replaceFirst(
            '\napply_standard_settings',
            '\nset_target_properties(\${BINARY_NAME} PROPERTIES SOURCES main.cpp)\napply_standard_settings',
          ),
          message: 'main.cpp',
        ),
        (
          name: 'the call does not list main.cpp',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32\n  "Runner.rc"\n)',
          ),
          message: 'main.cpp',
        ),
        (
          name: 'the call lists Runner.rc with a path',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32\n  "main.cpp"\n'
            '  "runner/Runner.rc"\n)',
          ),
          message: 'Runner.rc',
        ),
        (
          name: 'main.cpp is also listed as ./main.cpp',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32\n  "main.cpp"\n  "./main.cpp"\n  "Runner.rc"\n)',
          ),
          message: 'main.cpp',
        ),
        (
          name: 'Runner.rc is also listed as an alias',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32\n  "main.cpp"\n  "Runner.rc"\n  "./Runner.rc"\n)',
          ),
          message: 'Runner.rc',
        ),
        (
          name: 'main.cpp is listed with another case',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32\n  "main.cpp"\n  "Main.cpp"\n  "Runner.rc"\n)',
          ),
          message: 'main.cpp',
        ),
        (
          name: 'main.cpp is also listed in a folder',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32\n  "main.cpp"\n  "sub/../main.cpp"\n  "Runner.rc"\n)',
          ),
          message: 'main.cpp',
        ),
        (
          name: 'main.cpp is also listed after the source dir with an alias',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32\n  "main.cpp"\n  "\${CMAKE_CURRENT_SOURCE_DIR}/./main.cpp"\n  "Runner.rc"\n)',
          ),
          message: 'main.cpp',
        ),
        (
          name: 'two sources are on one line',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32\n  "main.cpp" "./main.cpp"\n  "Runner.rc"\n)',
          ),
          message: 'main.cpp',
        ),
        (
          name: 'a source has a comment after it',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32\n  "main.cpp"\n  "Runner.rc" # resources\n)',
          ),
          message: 'Runner.rc',
        ),
        (
          name: 'there is no call',
          source: 'project(runner)\n',
          message: 'add_executable',
        ),
        (
          name: 'the call is only commented out',
          source: '# add_executable(\${BINARY_NAME} WIN32\n#   "a.cpp"\n# )\n',
          message: 'add_executable',
        ),
        (
          name: 'there are two calls',
          source: '${_pristine()}\n$_call\n',
          message: 'more than one',
        ),
        (
          name: 'the call is on one line',
          source: _pristine(r'add_executable(${BINARY_NAME} WIN32 "a.cpp")'),
          message: 'add_executable',
        ),
        (
          name: 'the first line of the call has the sources',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32 "a.cpp"\n  "b.cpp"\n)',
          ),
          message: 'add_executable',
        ),
        (
          name: 'the call is in upper case',
          source: _pristine(
            'ADD_EXECUTABLE(\${BINARY_NAME} WIN32\n  "a.cpp"\n)',
          ),
          message: 'add_executable',
        ),
        (
          name: 'the call is not closed on a line of its own',
          source: _pristine('add_executable(\${BINARY_NAME} WIN32\n  "a.cpp")'),
          message: 'closing',
        ),
        (
          name: 'the call is not closed',
          source: 'add_executable(\${BINARY_NAME} WIN32\n  "a.cpp"\n',
          message: 'closing',
        ),
        (
          name: 'the closing parenthesis has a comment after it',
          source: _pristine(
            'add_executable(\${BINARY_NAME} WIN32\n  "a.cpp"\n) # sources',
          ),
          message: 'closing',
        ),
      ];

      for (final rejected in cases) {
        test(rejected.name, () {
          expect(
            () => _edit(rejected.source),
            throwsA(
              isA<UnsupportedRunnerLayoutException>()
                  .having(
                    (e) => e.path,
                    'path',
                    'windows/runner/CMakeLists.txt',
                  )
                  .having(
                    (e) => e.toString(),
                    'message',
                    allOf(
                      contains(rejected.message),
                      contains('Then run flavorizr again.'),
                    ),
                  ),
            ),
          );
        });
      }

      test('the markers do not form a region', () {
        expect(
          () => _edit('$_begin\n${_pristine()}'),
          throwsA(isA<MalformedResourceException>()),
        );
        expect(
          () => _edit('${_pristine()}$_end\n'),
          throwsA(isA<MalformedResourceException>()),
        );
      });
    });

    group('ownedContent', () {
      test('is the region, and nothing else of the file', () {
        final patched = _edit(_pristine());

        expect(
          WindowsRunnerCMakeListsEditor.ownedContent(patched),
          _region(_titles).split('\n').map((line) => line.trim()).join('\n'),
        );
        expect(
          WindowsRunnerCMakeListsEditor.ownedContent('# mine\n$patched'),
          WindowsRunnerCMakeListsEditor.ownedContent(patched),
        );
      });

      test('is empty for a file with no region', () {
        expect(WindowsRunnerCMakeListsEditor.ownedContent(_pristine()), '');
      });

      test('changes with a hand edit of the region', () {
        final patched = _edit(_pristine());

        expect(
          WindowsRunnerCMakeListsEditor.ownedContent(
            patched.replaceFirst('Apple App', 'Mine'),
          ),
          isNot(WindowsRunnerCMakeListsEditor.ownedContent(patched)),
        );
      });
    });
