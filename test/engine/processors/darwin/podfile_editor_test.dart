      _defaults,
      before: ["# project 'Runner', {", "  # project 'Runner', {"],
    ),
    flavors: ['apple'],
    expected: _podfile(
      [
        ..._region(_flavorEntries(['apple'])),
        ..._defaults,
      ],
      before: ["# project 'Runner', {", "  # project 'Runner', {"],
    ),
  ),
  (
    name:
        'does not look in a heredoc for the mapping line, nor in a block '
        'comment',
    source: _podfile(
      _defaults,
      before: [
        'script = <<~RUBY',
        "  project 'Runner', {",
        'RUBY',
        '=begin',
        "project 'Runner', {",
        '=end',
      ],
    ),
    flavors: ['apple'],
    expected: _podfile(
      [
        ..._region(_flavorEntries(['apple'])),
        ..._defaults,
      ],
      before: [
        'script = <<~RUBY',
        "  project 'Runner', {",
        'RUBY',
        '=begin',
        "project 'Runner', {",
        '=end',
      ],
    ),
  ),
  (
    name: 'goes through two heredocs that are opened on one line',
    source: _podfile(
