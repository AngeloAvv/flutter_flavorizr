/// [text] as the variants of a layout are told: LF, CRLF and no line break
/// at the end.
List<(String, String Function(String))> get _variants => [
  ('LF', (text) => text),
  ('CRLF', (text) => text.replaceAll('\n', '\r\n')),
  (
    'no line break at the end of the file',
    (text) => text.endsWith('\n') ? text.substring(0, text.length - 1) : text,
  ),
];

void main() {
  group('PodfileEditor.withFlavorMappings', () {
    for (final layout in [..._supported, ..._lexicalSupported]) {
      group(layout.name, () {
        for (final (variant, change) in _variants) {
          test(variant, () {
            final source = change(_lines(layout.source));
            final expected = change(_lines(layout.expected));

            final patched = PodfileEditor.withFlavorMappings(
              source,
              layout.flavors,
              path: _path,
            );

            expect(patched, expected);
            expect(
              PodfileEditor.withFlavorMappings(
                patched,
                layout.flavors,
                path: _path,
              ),
              patched,
              reason: 'running it again changes nothing',
            );
          });
        }
      });
    }

    test('a Podfile that has the region up to date is returned as it is, '
        'whatever its indentation', () {
      final source = _lines(
        _podfile([
          ..._region(_flavorEntries(['apple'], indent: '\t'), indent: '\t'),
          ..._defaults,
        ]),
      );

      expect(
        PodfileEditor.withFlavorMappings(source, ['apple'], path: _path),
        source,
      );
    });

    test('what a 2.x run wrote is adopted with the markers as the only '
        'difference, when it kept the default mappings', () {
      final source = _lines(
        _podfile([
          ..._flavorEntries(['apple', 'banana']),
          ..._defaults,
        ]),
      );

      final patched = PodfileEditor.withFlavorMappings(source, [
        'apple',
        'banana',
      ], path: _path);

      expect(
        patched.split('\n').where((line) => !line.contains('flavorizr')),
        source.split('\n'),
      );
    });

    test('the template of flutter create gets the region in the mapping and '
        'is the same everywhere else', () {
      final source = File(
        'test_resources/darwin/podfile_test/PodfileOriginal',
      ).readAsStringSync();

      final patched = PodfileEditor.withFlavorMappings(source, [
        'apple',
        'banana',
      ], path: _path);
      final lines = patched.split('\n');
      final begin = lines.indexOf('  $_begin');
      final end = lines.indexOf('  $_end');

      expect(begin, greaterThan(0));
      expect(
        lines.sublist(begin + 1, end),
        _flavorEntries(['apple', 'banana']),
      );
      expect([
        ...lines.sublist(0, begin),
        ...lines.sublist(end + 1),
      ], source.split('\n'));
    });

    test('keeps what the user has outside the region, a mapping of their '
        'own included', () {
      final source = _lines(
        _podfile([..._defaults, "  'Debug-mine' => :debug,"]),
      );

      final patched = PodfileEditor.withFlavorMappings(source, [
        'apple',
      ], path: _path);

      expect(patched, contains("  'Debug-mine' => :debug,"));
      expect(
        PodfileEditor.withFlavorMappings(patched, [], path: _path),
        source,
      );
    });

    for (final layout in [..._unsafe, ..._lexicalUnsafe]) {
      for (final (variant, change) in _variants) {
        test('refuses ${layout.name}, and says what to change ($variant)', () {
          expect(
            () => PodfileEditor.withFlavorMappings(
              change(_lines(layout.source)),
              ['apple'],
              path: _path,
            ),
            throwsA(
              isA<UnsafePodfileException>()
                  .having((e) => e.path, 'path', _path)
                  .having(
                    (e) => '${e.reason}\n${e.fix}',
                    'reason and fix',
                    contains(layout.reason),
                  )
                  .having(
                    (e) => e.toString(),
                    'message',
                    allOf(contains(_path), contains('run flavorizr again')),
                  ),
            ),
          );
        });
      }
    }
  });

  group('PodfileEditor.ownedContent', () {
    test('is the lines of the region, trimmed, and nothing else', () {
      final source = _lines(
        _podfile([
          ..._region(_flavorEntries(['apple'])),
          ..._defaults,
        ]),
      );

      expect(
        PodfileEditor.ownedContent(source),
        [
          _begin,
          ..._flavorEntries(['apple']).map((line) => line.trim()),
          _end,
        ].join('\n'),
      );
    });

    test('does not change with what the user edits outside the region, or '
        'with the indentation and the line endings of the region', () {
      final source = _lines(
        _podfile([
          ..._region(_flavorEntries(['apple'])),
          ..._defaults,
        ]),
      );
      final edited = _lines(
        _podfile(
          [
            ..._region(_flavorEntries(['apple'], indent: '\t'), indent: '\t'),
            "  'Debug-mine' => :debug,",
          ],
          before: ['# mine'],
        ),
      ).replaceAll('\n', '\r\n');

      expect(
        PodfileEditor.ownedContent(edited),
        PodfileEditor.ownedContent(source),
      );
    });

    test('changes with what is inside the region', () {
      final source = _lines(_podfile(_region(_flavorEntries(['apple']))));

      expect(
        PodfileEditor.ownedContent(source.replaceAll('apple', 'banana')),
        isNot(PodfileEditor.ownedContent(source)),
      );
    });

    test('is empty when there is no region', () {
      expect(PodfileEditor.ownedContent(_lines(_podfile(_defaults))), '');
    });

    test('does not throw when the markers do not form a region, and then '
        'differs from a good region', () {
      final broken = _lines(_podfile(['  $_begin']));
      final good = _lines(_podfile(_region(const [])));

      expect(
        PodfileEditor.ownedContent(broken),
        isNot(PodfileEditor.ownedContent(good)),
      );
    });
  });
}
