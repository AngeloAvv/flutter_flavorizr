      before: [
        'both = [<<-ONE, <<TWO]',
        "  project 'Runner', {",
        '  ONE',
        "project 'Runner', {",
        'TWO',
      ],
    ),
    flavors: ['apple'],
    expected: _podfile(
      [
        ..._region(_flavorEntries(['apple'])),
        ..._defaults,
      ],
      before: [
        'both = [<<-ONE, <<TWO]',
        "  project 'Runner', {",
        '  ONE',
        "project 'Runner', {",
        'TWO',
      ],
    ),
  ),
  (
    name:
        'leaves post_install, targets and everything else alone, wherever '
        'the mapping is',
