import 'dart:io';

import 'package:flutter_flavorizr/src/engine/processors/darwin/podfile_editor.dart';
import 'package:flutter_flavorizr/src/exception/unsafe_podfile_exception.dart';
import 'package:flutter_test/flutter_test.dart';

const _path = 'ios/Podfile';

const _begin =
    '# ----- BEGIN flavorizr (autogenerated by flutter_flavorizr) -----';
const _end = '# ----- END flavorizr (autogenerated by flutter_flavorizr) -----';

/// Lines, each one ended by a line break.
String _lines(List<String> lines) => '${lines.join('\n')}\n';

const _defaults = [
  "  'Debug' => :debug,",
  "  'Profile' => :release,",
  "  'Release' => :release,",
];

final _deeper = [for (final line in _defaults) '  $line'];

const _tabbed = [
  "\t'Debug' => :debug,",
  "\t'Profile' => :release,",
  "\t'Release' => :release,",
];

/// The mappings of [flavors], the way flavorizr writes them.
List<String> _flavorEntries(Iterable<String> flavors, {String indent = '  '}) =>
    [
      for (final flavor in flavors) ...[
        "$indent'Debug-$flavor' => :debug,",
        "$indent'Profile-$flavor' => :release,",
        "$indent'Release-$flavor' => :release,",
      ],
    ];

/// A region that holds [entries], which are already indented.
List<String> _region(List<String> entries, {String indent = '  '}) => [
  '$indent$_begin',
  ...entries,
  '$indent$_end',
];

/// What `flutter create` writes around the mapping.
List<String> _podfile(
  List<String> mapping, {
  List<String> before = const [],
  String indent = '',
}) => [
  "# platform :ios, '12.0'",
  '',
  ...before,
  "${indent}project 'Runner', {",
  ...mapping,
  '$indent}',
  '',
  'def flutter_root',
  "  File.expand_path(File.join('..', 'Flutter'), __FILE__)",
  'end',
  '',
  "target 'Runner' do",
  '  use_frameworks!',
  'end',
  '',
  'post_install do |installer|',
  '  installer.pods_project.targets.each do |target|',
  '    flutter_additional_ios_build_settings(target)',
  '  end',
  'end',
];

typedef _Case = ({
  String name,
  List<String> source,
  List<String> flavors,
  List<String> expected,
});

/// Where the layouts of the editor are told, one row for each class. A row is
/// run with LF and with CRLF line endings, and with and without a line break
/// at the end of the file, and the result is checked to be stable.
final _supported = <_Case>[
  (
    name:
        'adds the region right after the mapping line, and keeps the '
        'default mappings where they are',
    source: _podfile(_defaults),
    flavors: ['apple', 'banana'],
    expected: _podfile([
      ..._region(_flavorEntries(['apple', 'banana'])),
      ..._defaults,
    ]),
  ),
  (
    name: 'drops the mappings of a flavor that is not configured anymore',
    source: _podfile([
      ..._region(_flavorEntries(['apple', 'banana'])),
      ..._defaults,
    ]),
    flavors: ['apple'],
    expected: _podfile([
      ..._region(_flavorEntries(['apple'])),
      ..._defaults,
    ]),
  ),
  (
    name: 'adds the mappings of a flavor that was configured',
    source: _podfile([
      ..._region(_flavorEntries(['apple'])),
      ..._defaults,
    ]),
    flavors: ['apple', 'banana'],
    expected: _podfile([
      ..._region(_flavorEntries(['apple', 'banana'])),
      ..._defaults,
    ]),
  ),
  (
    name:
        'regenerates a region the user edited, where it is, and leaves '
        'what is around it alone',
    source: _podfile([
      '  # mine',
      "  'Debug-legacy' => :debug,",
      '  $_begin',
      "  'Debug-apple' => :release, # edited",
      '  $_end',
      ..._defaults,
    ]),
    flavors: ['apple'],
    expected: _podfile([
      '  # mine',
      "  'Debug-legacy' => :debug,",
      ..._region(_flavorEntries(['apple'])),
      ..._defaults,
    ]),
  ),
  (
    name:
        'removes the region when no flavor is left, and leaves the '
        'Podfile as flutter create writes it',
    source: _podfile([
      ..._region(_flavorEntries(['apple'])),
      ..._defaults,
    ]),
    flavors: [],
    expected: _podfile(_defaults),
  ),
  (
    name: 'does nothing without flavors and without a region',
    source: _podfile(_defaults),
    flavors: [],
    expected: _podfile(_defaults),
  ),
  (
    name:
        'puts the default mappings that are missing in the region, so that '
        'a Podfile that lost them has them again',
    source: _podfile(["  'Profile' => :release,"]),
    flavors: ['apple'],
    expected: _podfile([
      ..._region([
        "  'Debug' => :debug,",
        "  'Release' => :release,",
        ..._flavorEntries(['apple']),
      ]),
      "  'Profile' => :release,",
    ]),
  ),
  (
    name:
        'keeps the default mappings in the region when the last flavor goes, '
        'since nothing else has them',
    source: _podfile(
      _region([
        ..._defaults,
        ..._flavorEntries(['apple']),
      ]),
    ),
    flavors: [],
    expected: _podfile(_region(_defaults)),
  ),
  (
    name:
        'does not repeat a default mapping that is written with double '
        'quotes',
    source: _podfile([
      '  "Debug" => :debug,',
      '  "Profile" => :release,',
      '  "Release" => :release,',
    ]),
    flavors: ['apple'],
    expected: _podfile([
      ..._region(_flavorEntries(['apple'])),
      '  "Debug" => :debug,',
      '  "Profile" => :release,',
      '  "Release" => :release,',
    ]),
  ),
  (
    name:
        'adopts what a 2.x run wrote: the mappings it dropped the defaults '
        'for are the region now, in place, with the defaults back',
    source: _podfile(_flavorEntries(['apple', 'banana'])),
    flavors: ['apple', 'banana'],
    expected: _podfile(
      _region([
        ..._defaults,
        ..._flavorEntries(['apple', 'banana']),
      ]),
    ),
  ),
  (
    name:
        'adopts the lines of a 2.x run in place, and only the ones it '
        'would write itself',
    source: _podfile([
      "  'Debug-legacy' => :debug,",
      ..._flavorEntries(['apple']),
      "  'Release-banana' => :release,",
      ..._defaults,
    ]),
    flavors: ['apple'],
    expected: _podfile([
      "  'Debug-legacy' => :debug,",
      ..._region(_flavorEntries(['apple'])),
      "  'Release-banana' => :release,",
      ..._defaults,
    ]),
  ),
  (
    name: 'takes the indentation of the mapping, wherever it is',
    source: _podfile(_deeper, indent: '  '),
    flavors: ['apple'],
    expected: _podfile([
      ..._region(_flavorEntries(['apple'], indent: '    '), indent: '    '),
      ..._deeper,
    ], indent: '  '),
  ),
  (
    name: 'indents the region two spaces further than an empty mapping',
    source: _podfile([], indent: '  '),
    flavors: ['apple'],
    expected: _podfile(
      _region([
        ..._defaults.map((line) => '  $line'),
        ..._flavorEntries(['apple'], indent: '    '),
      ], indent: '    '),
      indent: '  ',
    ),
  ),
  (
    name: 'goes along with tabs',
    source: _podfile(_tabbed),
    flavors: ['apple'],
    expected: _podfile([
      ..._region(_flavorEntries(['apple'], indent: '\t'), indent: '\t'),
      ..._tabbed,
    ]),
  ),
  (
    name:
        'reads a mapping with comments, blank lines, a last entry without '
        'a comma and comments after the entries',
    source: _podfile([
      '  # the modes',
      '',
      "  'Debug' => :debug, # for debugging",
      "  'Profile' => :release,",
      "  'Release' => :release # no comma",
    ]),
    flavors: ['apple'],
    expected: _podfile([
      ..._region(_flavorEntries(['apple'])),
      '  # the modes',
      '',
      "  'Debug' => :debug, # for debugging",
      "  'Profile' => :release,",
      "  'Release' => :release # no comma",
    ]),
  ),
  (
    name: 'quotes the name of a flavor',
    source: _podfile(_defaults),
    flavors: ["it's"],
    expected: _podfile([
      ..._region([
        r"  'Debug-it\'s' => :debug,",
        r"  'Profile-it\'s' => :release,",
        r"  'Release-it\'s' => :release,",
