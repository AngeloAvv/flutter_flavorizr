import 'dart:io';

import 'package:flutter_flavorizr/src/engine/processors/linux/linux_cmake_lists_editor.dart';
import 'package:flutter_flavorizr/src/engine/processors/linux/linux_runner_cmake_lists_editor.dart';
import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';
import 'package:test/test.dart';

const _ids = {'apple': 'com.example.apple', 'banana': 'com.example.banana'};

const _begin =
    '# ----- BEGIN APPLICATION_ID (autogenerated by flutter_flavorizr) -----';
const _end =
    '# ----- END APPLICATION_ID (autogenerated by flutter_flavorizr) -----';

const _region =
    '$_begin\n'
    'if(DEFINED FLUTTER_APP_FLAVOR)\n'
    '  if(FLUTTER_APP_FLAVOR STREQUAL "apple")\n'
    '    set(APPLICATION_ID "com.example.apple")\n'
    '  elseif(FLUTTER_APP_FLAVOR STREQUAL "banana")\n'
    '    set(APPLICATION_ID "com.example.banana")\n'
    '  endif()\n'
    'endif()\n'
    '$_end';

const _pristine =
    'set(APPLICATION_ID "com.example.example")\n'
    '\n'
    r'set(FLUTTER_MANAGED_DIR "${CMAKE_CURRENT_SOURCE_DIR}/flutter")'
    '\n'
    r'add_subdirectory(${FLUTTER_MANAGED_DIR})'
    '\n'
    '\n'
    '# System-level dependencies.\n'
    'find_package(PkgConfig REQUIRED)\n';

String _read(String path) => File(path).readAsStringSync();

String _withoutBlankLines(String text) =>
    text.split('\n').where((line) => line.trim().isNotEmpty).join('\n');

void main() {
  group('LinuxCMakeListsEditor', () {
    test('adds the region after the flutter directory, which is the only '
        'thing it changes', () {
      final patched = LinuxCMakeListsEditor.withApplicationIds(_pristine, _ids);

      expect(
        patched,
        'set(APPLICATION_ID "com.example.example")\n'
        '\n'
        r'set(FLUTTER_MANAGED_DIR "${CMAKE_CURRENT_SOURCE_DIR}/flutter")'
        '\n'
        r'add_subdirectory(${FLUTTER_MANAGED_DIR})'
        '\n'
        '$_region\n'
        '\n'
        '# System-level dependencies.\n'
        'find_package(PkgConfig REQUIRED)\n',
      );
    });

    test('is the 2.x output on a pristine file, but for the blank lines 2.x '
        'added around the region', () {
      final source = _read(
        'test_resources/linux/cmake_lists_processor_test/CMakeLists.txt',
      );

      expect(
        _withoutBlankLines(
          LinuxCMakeListsEditor.withApplicationIds(source, _ids),
        ),
        _withoutBlankLines(
          _read(
            'test_resources/linux/cmake_lists_processor_test/CMakeLists_expected.txt',
          ),
        ),
      );
    });

    test('returns a file that is up to date as it is, 2.x ones included', () {
      final source = _read(
        'test_resources/linux/cmake_lists_processor_test/CMakeLists_expected.txt',
      );

      expect(LinuxCMakeListsEditor.withApplicationIds(source, _ids), source);
    });

    test('regenerates the region without the flavor that was removed, in '
        'place and with nothing else touched', () {
      final first = LinuxCMakeListsEditor.withApplicationIds(_pristine, _ids);

      final second = LinuxCMakeListsEditor.withApplicationIds(first, {
        'apple': 'com.example.apple',
      });

      expect(second, isNot(contains('banana')));
      expect(
        second,
        first.replaceFirst(
          '  elseif(FLUTTER_APP_FLAVOR STREQUAL "banana")\n'
              '    set(APPLICATION_ID "com.example.banana")\n',
          '',
        ),
      );
    });

    test('is idempotent, and keeps what the user wrote around the region', () {
      final edited = LinuxCMakeListsEditor.withApplicationIds(
        _pristine,
        _ids,
      ).replaceFirst('# System-level', '# mine\n# System-level');

      expect(LinuxCMakeListsEditor.withApplicationIds(edited, _ids), edited);
    });

    test('escapes the application id', () {
      expect(
        LinuxCMakeListsEditor.withApplicationIds(_pristine, {
          'apple': 'a"b\\c',
        }),
        contains(r'set(APPLICATION_ID "a\"b\\c")'),
      );
    });

    test('keeps the CRLF line endings of the file', () {
      final source = _pristine.replaceAll('\n', '\r\n');

      final patched = LinuxCMakeListsEditor.withApplicationIds(source, _ids);

      expect(patched.replaceAll('\r\n', ''), isNot(contains('\n')));
      expect(
        patched.replaceAll('\r\n', '\n'),
        LinuxCMakeListsEditor.withApplicationIds(_pristine, _ids),
      );
    });

    test('fails without the application id setter, which a region of '
        'flavorizr is not', () {
      for (final source in [
        r'add_subdirectory(${FLUTTER_MANAGED_DIR})'
            '\n',
        LinuxCMakeListsEditor.withApplicationIds(
          _pristine,
          _ids,
        ).replaceFirst('set(APPLICATION_ID "com.example.example")\n', ''),
      ]) {
        expect(
          () => LinuxCMakeListsEditor.withApplicationIds(source, _ids),
          throwsA(isA<MalformedResourceException>()),
        );
      }
    });

    test('writes a region that is balanced when there is no flavor to '
        'override', () {
      expect(
        LinuxCMakeListsEditor.withApplicationIds(_pristine, {}),
        contains('if(DEFINED FLUTTER_APP_FLAVOR)\nendif()\n$_end'),
      );
    });

    test('fails without the flutter directory', () {
      expect(
        () => LinuxCMakeListsEditor.withApplicationIds(
          'set(APPLICATION_ID "x")\n',
          _ids,
        ),
        throwsA(isA<MalformedResourceException>()),
      );
    });

    test('owns the region and nothing else', () {
      final patched = LinuxCMakeListsEditor.withApplicationIds(_pristine, _ids);

      // Trimmed, so that the indentation of the region is never drift.
      final owned = _region.split('\n').map((line) => line.trim()).join('\n');

      expect(LinuxCMakeListsEditor.ownedContent(patched), owned);
      expect(
        LinuxCMakeListsEditor.ownedContent(
          patched.replaceFirst('# System', '# mine\n# System'),
        ),
        owned,
      );
      expect(LinuxCMakeListsEditor.ownedContent(_pristine), '');
    });
  });

  group('LinuxRunnerCMakeListsEditor', () {
    const begin =
        '# ----- BEGIN FLUTTER_APP_FLAVOR (autogenerated by flutter_flavorizr) -----';
    const end =
        '# ----- END FLUTTER_APP_FLAVOR (autogenerated by flutter_flavorizr) -----';
    const region =
        '$begin\n'
        'if(DEFINED FLUTTER_APP_FLAVOR AND NOT FLUTTER_APP_FLAVOR STREQUAL "")\n'
        r'  add_definitions(-DFLUTTER_APP_FLAVOR="${FLUTTER_APP_FLAVOR}")'
        '\n'
        'endif()\n'
        '$end';

    const pristine =
        '# Add preprocessor definitions for the application ID.\n'
        r'add_definitions(-DAPPLICATION_ID="${APPLICATION_ID}")'
        '\n'
        '\n'
        '# Add dependency libraries.\n';

    test('adds the region after the application id definition', () {
      expect(
        LinuxRunnerCMakeListsEditor.withFlavorDefinition(pristine),
        '# Add preprocessor definitions for the application ID.\n'
        r'add_definitions(-DAPPLICATION_ID="${APPLICATION_ID}")'
        '\n'
        '$region\n'
        '\n'
        '# Add dependency libraries.\n',
      );
    });

    test('is the 2.x output on a pristine file, but for the blank lines 2.x '
        'added around the region, and leaves a 2.x file alone', () {
      final source = _read(
        'test_resources/linux/runner_cmake_lists_processor_test/CMakeLists.txt',
      );
      final expected = _read(
        'test_resources/linux/runner_cmake_lists_processor_test/CMakeLists_expected.txt',
      );

      expect(
        _withoutBlankLines(
          LinuxRunnerCMakeListsEditor.withFlavorDefinition(source),
        ),
        _withoutBlankLines(expected),
      );
      expect(
        LinuxRunnerCMakeListsEditor.withFlavorDefinition(expected),
        expected,
      );
    });

    test('fails without the application id definition', () {
      expect(
        () => LinuxRunnerCMakeListsEditor.withFlavorDefinition('a\n'),
        throwsA(isA<MalformedResourceException>()),
      );
    });

    test('owns the region and nothing else', () {
      final patched = LinuxRunnerCMakeListsEditor.withFlavorDefinition(
        pristine,
      );

      expect(
        LinuxRunnerCMakeListsEditor.ownedContent(patched),
        region.split('\n').map((line) => line.trim()).join('\n'),
      );
      expect(LinuxRunnerCMakeListsEditor.ownedContent(pristine), '');
    });
  });
}
