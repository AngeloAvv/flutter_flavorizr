import 'package:flutter_test/flutter_test.dart';
import 'package:path/path.dart' as p;

import '../../../test_utils.dart';

/// A processor of the group, the file it patches, a pristine one and what must
/// be in it once it is patched.
typedef _Case = ({
  String id,
  FlavorizrProcessor processor,
  String path,
  Set<String> after,
  String pristine,
  List<String> expected,
});

String _resource(String path) =>
    File('test_resources/linux/$path').readAsStringSync();

final _cases = <_Case>[
  (
    id: 'linux:cmake',
    processor: const LinuxCMakeListsPatchProcessor(),
    path: K.linuxCMakeListsPath,
    after: {},
    pristine: _resource('cmake_lists_processor_test/CMakeLists.txt'),
    expected: ['com.example.apple', 'com.example.banana'],
  ),
  (
    id: 'linux:runnerCmake',
    processor: const LinuxRunnerCMakeListsPatchProcessor(),
    path: K.linuxRunnerCMakeListsPath,
    after: {'linux:cmake'},
    pristine: _resource('runner_cmake_lists_processor_test/CMakeLists.txt'),
    expected: ['add_definitions(-DFLUTTER_APP_FLAVOR='],
  ),
  (
    id: 'linux:myApplication',
    processor: const LinuxMyApplicationPatchProcessor(),
    path: K.linuxMyApplicationPath,
    after: {'linux:runnerCmake'},
    pristine: _resource('my_application_processor_test/my_application.cc'),
    expected: ['Apple App', 'Banana App'],
  ),
];

void main() {
  late Directory root;
  late Directory projectRoot;
  late FlavorizrContext ctx;

  setUp(() {
    final temp = Directory.systemTemp.createTempSync('flavorizr_linux_');
    addTearDown(() => temp.deleteSync(recursive: true));

    root = Directory(p.join(temp.path, 'shadow'))..createSync();
    projectRoot = Directory(p.join(temp.path, 'project'))..createSync();

    ctx = FlavorizrContext(
      config: TestUtils.parseFlavorizr('test_resources/linux/pubspec'),
      root: root,
      projectRoot: projectRoot,
      logger: TestUtils.quietLogger(),
    );
  });

  for (final testCase in _cases) {
    group('${testCase.processor.runtimeType}', () {
      File file(Directory base) => File(p.join(base.path, testCase.path));

      test('is the `${testCase.id}` processor, which orders after the ones '
          'before it but needs none', () {
        expect(testCase.processor.id, testCase.id);
        expect(testCase.processor.dependsOn, isEmpty);
        expect(testCase.processor.after, testCase.after);
        expect(testCase.processor.requires, isEmpty);
      });

      test('patches the file and tracks it as patched', () async {
        file(root)
          ..createSync(recursive: true)
          ..writeAsStringSync(testCase.pristine);

        await testCase.processor.apply(ctx);

        final patched = file(root).readAsStringSync();

        expect(patched, contains('autogenerated by flutter_flavorizr'));
        for (final expected in testCase.expected) {
          expect(patched, contains(expected));
        }
        expect(ctx.tracked, [Artifact.patched(testCase.path)]);
      });

      test('reads the shadow workspace, never the real project nor the '
          'working directory', () async {
        file(root)
          ..createSync(recursive: true)
          ..writeAsStringSync(testCase.pristine);
        file(projectRoot)
          ..createSync(recursive: true)
          ..writeAsStringSync('real');

        await testCase.processor.apply(ctx);

        expect(file(projectRoot).readAsStringSync(), 'real');
        expect(File(testCase.path).existsSync(), isFalse);
      });

      test('does not write a file that is already up to date', () async {
        file(root)
          ..createSync(recursive: true)
          ..writeAsStringSync(testCase.pristine);
        await testCase.processor.apply(ctx);
        final modified = DateTime.utc(2020);
        file(root).setLastModifiedSync(modified);

        await testCase.processor.apply(ctx);

        expect(file(root).lastModifiedSync().toUtc(), modified);
      });

      test(
        'keeps the byte order mark and the line endings of the file',
        () async {
          file(root)
            ..createSync(recursive: true)
            ..writeAsBytesSync([
              0xef,
              0xbb,
              0xbf,
              ...utf8.encode(testCase.pristine.replaceAll('\n', '\r\n')),
            ]);

          await testCase.processor.apply(ctx);

          final bytes = file(root).readAsBytesSync();
          final text = utf8.decode(bytes.sublist(3));

          expect(bytes.take(3), [0xef, 0xbb, 0xbf]);
          expect(text.replaceAll('\r\n', ''), isNot(contains('\n')));
          expect(text, contains('autogenerated by flutter_flavorizr'));
        },
      );

      test('fails when there is no file', () {
        expect(
          testCase.processor.apply(ctx),
          throwsA(isA<FileNotFoundException>()),
        );
      });

      test('fails on a file it cannot edit', () {
        file(root)
          ..createSync(recursive: true)
          ..writeAsStringSync('nothing to anchor to\n');

        expect(
          testCase.processor.apply(ctx),
          throwsA(isA<MalformedResourceException>()),
        );
      });
    });
  }
}
