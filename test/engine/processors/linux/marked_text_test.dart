import 'package:flutter_flavorizr/src/engine/processors/linux/marked_text.dart';
import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';
import 'package:test/test.dart';

const _marker = RegionMarker('X', comment: '#');
const _other = RegionMarker('Y', comment: '//');

const _begin = '# ----- BEGIN X (autogenerated by flutter_flavorizr) -----';
const _end = '# ----- END X (autogenerated by flutter_flavorizr) -----';

TextLine? _after(List<TextLine> lines, String text) =>
    lines.where((line) => line.text.trim() == text).firstOrNull;

void main() {
  group('RegionMarker', () {
    test('writes the markers 2.x writes', () {
      expect(_marker.begin, _begin);
      expect(_marker.end, _end);
      expect(
        _other.begin,
        '// ----- BEGIN Y (autogenerated by flutter_flavorizr) -----',
      );
    });
  });

  group('MarkedText.upsert', () {
    test('inserts the region with the indentation it is told, instead of the '
        'one of the anchor', () {
      final text = MarkedText('a\nanchor\nb\n', [_marker]);

      expect(
        text.upsert(
          _marker,
          ['x'],
          anchor: (lines) => _after(lines, 'anchor'),
          indentation: '    ',
        ),
        'a\nanchor\n    $_begin\n    x\n    $_end\nb\n',
      );
    });

    test('keeps the indentation of a region that is there, whatever it is '
        'told', () {
      final text = MarkedText('a\n  $_begin\n  old\n  $_end\nb\n', [_marker]);

      expect(
        text.upsert(
          _marker,
          ['new'],
          anchor: (lines) => null,
          indentation: '        ',
        ),
        'a\n  $_begin\n  new\n  $_end\nb\n',
      );
    });

    test('inserts the region after the anchor, with its indentation', () {
      final text = MarkedText('a\n  anchor\nb\n', [_marker]);

      expect(
        text.upsert(_marker, [
          'if(x)',
          '  y()',
          'endif()',
        ], anchor: (lines) => _after(lines, 'anchor')),
        'a\n  anchor\n'
        '  $_begin\n  if(x)\n    y()\n  endif()\n  $_end\n'
        'b\n',
      );
    });

    test('adds nothing but the region, not even a blank line', () {
      final text = MarkedText('anchor\n\nrest\n', [_marker]);

      expect(
        text.upsert(_marker, ['x'], anchor: (lines) => _after(lines, 'anchor')),
        'anchor\n$_begin\nx\n$_end\n\nrest\n',
      );
    });

    test('inserts after an anchor that ends the file, with or without a '
        'line break, and keeps the line endings of the file', () {
      expect(
        MarkedText('anchor', [
          _marker,
        ]).upsert(_marker, ['x'], anchor: (lines) => _after(lines, 'anchor')),
        'anchor\n$_begin\nx\n$_end',
      );
      expect(
        MarkedText('anchor\r\n', [
          _marker,
        ]).upsert(_marker, ['x'], anchor: (lines) => _after(lines, 'anchor')),
        'anchor\r\n$_begin\r\nx\r\n$_end\r\n',
      );
    });

    test('replaces a region that is not up to date in place', () {
      final text = MarkedText('a\n  $_begin\n  old\n  $_end\nb\n', [_marker]);

      expect(
        text.upsert(_marker, ['new', '  deeper'], anchor: (lines) => null),
        'a\n  $_begin\n  new\n    deeper\n  $_end\nb\n',
      );
    });

    test('returns the source as it is when the region is up to date, '
        'whatever its indentation', () {
      final source = 'a\n\t$_begin\n    x\n$_end\nb';
      final text = MarkedText(source, [_marker]);

      expect(text.upsert(_marker, ['x'], anchor: (lines) => null), source);
    });

    test('keeps the first region, replaces it and drops the others', () {
      final source = '$_begin\nold\n$_end\nmid\n$_begin\nold\n$_end\nend\n';

      expect(
        MarkedText(source, [
          _marker,
        ]).upsert(_marker, ['x'], anchor: (lines) => null),
        '$_begin\nx\n$_end\nmid\nend\n',
      );
    });

    test('never looks for the anchor inside a region', () {
      final text = MarkedText('a\n$_begin\nanchor\n$_end\n', [_marker]);

      expect(text.outside.map((line) => line.text), ['a']);
    });

    test('fails when there is no region and no anchor', () {
      expect(
        () => MarkedText('a\n', [
          _marker,
        ]).upsert(_marker, ['x'], anchor: (lines) => null),
        throwsA(isA<MalformedResourceException>()),
      );
    });

    test('fails on markers that do not form regions', () {
      for (final source in [
        '$_begin\nx\n',
        '$_end\n',
        '$_begin\n$_begin\n$_end\n',
        '$_end\n$_begin\n',
      ]) {
        expect(
          () => MarkedText(source, [
            _marker,
          ]).upsert(_marker, ['x'], anchor: (lines) => null),
          throwsA(isA<MalformedResourceException>()),
          reason: source,
        );
      }
    });

    test('a region of another marker is left alone', () {
      final other = '${_other.begin}\nx\n${_other.end}\n';

      expect(
        MarkedText('a\n$other', [
          _marker,
          _other,
        ]).upsert(_marker, ['x'], anchor: (lines) => _after(lines, 'a')),
        'a\n$_begin\nx\n$_end\n$other',
      );
    });
  });

  group('MarkedText.remove', () {
    test('removes every region of the marker, lines included', () {
      final source = 'a\n$_begin\nx\n$_end\nb\n$_begin\ny\n$_end\n';

      expect(MarkedText(source, [_marker]).remove(_marker), 'a\nb\n');
    });

    test('returns the source as it is when there is no region', () {
      expect(MarkedText('a\n', [_marker]).remove(_marker), 'a\n');
    });
  });

  group('MarkedText.ownedContent', () {
    test('is the trimmed lines of every region, in file order', () {
      final source =
          'a\n  ${_other.begin}\n  y\n  ${_other.end}\n'
          '$_begin\r\n x \r\n$_end\nb\n';

      expect(
        MarkedText.ownedContent(source, [_marker, _other]),
        [_other.begin, 'y', _other.end, _begin, 'x', _end].join('\n'),
      );
    });

    test('is empty when there is no region', () {
      expect(MarkedText.ownedContent('a\n', [_marker]), '');
    });

    test('does not throw on markers that do not form regions', () {
      expect(
        MarkedText.ownedContent('$_begin\nx\n', [_marker]),
        contains('<unbalanced markers>'),
      );
    });
  });
}
