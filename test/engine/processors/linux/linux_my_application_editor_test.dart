import 'dart:io';

import 'package:flutter_flavorizr/src/engine/processors/linux/linux_my_application_editor.dart';
import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';
import 'package:flutter_flavorizr/src/processors/linux/linux_my_application_processor.dart';
import 'package:flutter_test/flutter_test.dart';

import '../../../test_utils.dart';

const _titles = {'apple': 'Apple App', 'banana': 'Banana App'};

String _read(String path) => File(path).readAsStringSync();

String _begin(String name) =>
    '// ----- BEGIN $name (autogenerated by flutter_flavorizr) -----';
String _end(String name) =>
    '// ----- END $name (autogenerated by flutter_flavorizr) -----';

/// What a `flutter create` run writes: the title is two string literals.
final _pristine = _read(
  'test_resources/linux/my_application_processor_test/my_application.cc',
);

/// What a 2.x run wrote, or a template that declares the title: a variable and
/// a region that overrides it.
final _withVariable = _read(
  'test_resources/linux/my_application_processor_test/my_application_expected.cc',
);

final _plain = _pristine.replaceFirst(
  '  if (use_header_bar) {\n',
  '  const gchar* window_title = "example";\n  if (use_header_bar) {\n',
);

/// The lines of [text] that are not inside a region.
List<String> _outsideTheRegions(String text) {
  final lines = <String>[];
  var inside = false;

  for (final line in text.split('\n')) {
    if (line.contains('BEGIN ')) inside = true;
    if (!inside) lines.add(line);
    if (line.contains('END ')) inside = false;
  }

  return lines;
}

void main() {
  group('LinuxMyApplicationEditor on a `flutter create` file', () {
    final patched = LinuxMyApplicationEditor.withWindowTitles(
      _pristine,
      _titles,
    );

    test('adds regions and changes nothing outside them', () {
      expect(_outsideTheRegions(patched), _outsideTheRegions(_pristine));
      expect(patched, isNot(contains('const gchar* window_title')));
    });

    test('overrides the title of the header bar and of the window, each '
        'right after the literal that sets it', () {
      expect(
        patched,
        contains(
          '    gtk_header_bar_set_title(header_bar, "example");\n'
          '    ${_begin('header_bar_title')}\n'
          '    #ifdef FLUTTER_APP_FLAVOR\n'
          '    if (g_strcmp0(FLUTTER_APP_FLAVOR, "apple") == 0) {\n'
          '      gtk_header_bar_set_title(header_bar, "Apple App");\n'
          '    } else if (g_strcmp0(FLUTTER_APP_FLAVOR, "banana") == 0) {\n'
          '      gtk_header_bar_set_title(header_bar, "Banana App");\n'
          '    }\n'
          '    #endif\n'
          '    ${_end('header_bar_title')}\n',
        ),
      );
      expect(
        patched,
        contains(
          '    gtk_window_set_title(window, "example");\n'
          '    ${_begin('plain_window_title')}\n'
          '    #ifdef FLUTTER_APP_FLAVOR\n'
          '    if (g_strcmp0(FLUTTER_APP_FLAVOR, "apple") == 0) {\n'
          '      gtk_window_set_title(window, "Apple App");\n'
          '    } else if (g_strcmp0(FLUTTER_APP_FLAVOR, "banana") == 0) {\n'
          '      gtk_window_set_title(window, "Banana App");\n'
          '    }\n'
          '    #endif\n'
          '    ${_end('plain_window_title')}\n',
        ),
      );
    });

    test('is idempotent', () {
      expect(
        LinuxMyApplicationEditor.withWindowTitles(patched, _titles),
        patched,
      );
    });

    test('regenerates the regions without the flavor that was removed', () {
      final removed = LinuxMyApplicationEditor.withWindowTitles(patched, {
        'apple': 'Apple App',
      });

      expect(removed, isNot(contains('banana')));
      expect(removed, isNot(contains('Banana App')));
      expect(_outsideTheRegions(removed), _outsideTheRegions(_pristine));
      expect(
        LinuxMyApplicationEditor.withWindowTitles(
          LinuxMyApplicationEditor.withWindowTitles(_pristine, {
            'apple': 'Apple App',
          }),
          _titles,
        ),
        patched,
      );
    });

    test('escapes the titles', () {
      expect(
        LinuxMyApplicationEditor.withWindowTitles(_pristine, {
          'apple': 'The "App"',
        }),
        contains(r'"The \"App\""'),
      );
    });

    test('writes regions that are balanced when there is no flavor to '
        'override', () {
      final patched = LinuxMyApplicationEditor.withWindowTitles(_pristine, {});

      expect(
        patched,
        contains(
          '    #ifdef FLUTTER_APP_FLAVOR\n'
          '    #endif\n'
          '    ${_end('header_bar_title')}',
        ),
      );
      expect(_outsideTheRegions(patched), _outsideTheRegions(_pristine));
    });

    test('fails when the title is set by neither a variable nor a literal', () {
      expect(
        () => LinuxMyApplicationEditor.withWindowTitles(
          'int main() {}\n',
          _titles,
        ),
        throwsA(isA<MalformedResourceException>()),
      );
    });
  });

  group('LinuxMyApplicationEditor on a file with a title variable', () {
    test('adds the region right after the variable, as 2.x did', () {
      final source = _withVariable.replaceAll(
        RegExp(
          r'  // ----- BEGIN window_title.*?END window_title[^\n]*\n',
          dotAll: true,
        ),
        '',
      );

      expect(
        LinuxMyApplicationEditor.withWindowTitles(source, _titles),
        _withVariable,
      );
    });

    test('leaves a file flavorized by 2.x as it is', () {
      expect(
        LinuxMyApplicationEditor.withWindowTitles(_withVariable, _titles),
        _withVariable,
      );
    });

    test('regenerates the region in place when a flavor is removed', () {
      final removed = LinuxMyApplicationEditor.withWindowTitles(_withVariable, {
        'apple': 'Apple App',
      });

      expect(removed, isNot(contains('banana')));
      expect(_outsideTheRegions(removed), _outsideTheRegions(_withVariable));
    });

    test('drops the regions of a file that had no variable, which the user '
        'then added', () {
      final flavorized = LinuxMyApplicationEditor.withWindowTitles(
        _pristine,
        _titles,
      );
      final withVariable = flavorized.replaceFirst(
        '  if (use_header_bar) {\n',
        '  const gchar* window_title = "example";\n  if (use_header_bar) {\n',
      );

      final patched = LinuxMyApplicationEditor.withWindowTitles(
        withVariable,
        _titles,
      );

      expect(patched, isNot(contains('header_bar_title')));
      expect(patched, isNot(contains('plain_window_title')));
      expect(
        patched,
        contains(
          '  const gchar* window_title = "example";\n'
          '  ${_begin('window_title')}\n',
        ),
      );
    });

    test('adds the region to a variable that is declared with the plain '
        'template, which is what 2.x did byte for byte', () {
      final patched = LinuxMyApplicationEditor.withWindowTitles(
        _plain,
        _titles,
      );
      final legacy = LinuxMyApplicationProcessor(
        input: _plain,
        config: TestUtils.parseFlavorizr('test_resources/linux/pubspec'),
        logger: TestUtils.quietLogger(),
      ).execute();

      expect(_outsideTheRegions(patched), _outsideTheRegions(_plain));
      expect(patched, contains(_begin('window_title')));
      expect(patched, legacy);
    });
  });

  group('LinuxMyApplicationEditor.ownedContent', () {
    test('is the regions and nothing else, whatever the mode', () {
      for (final source in [_pristine, _withVariable]) {
        final patched = LinuxMyApplicationEditor.withWindowTitles(
          source,
          _titles,
        );
        final owned = LinuxMyApplicationEditor.ownedContent(patched);

        expect(owned, contains('Apple App'));
        expect(owned, isNot(contains('gtk_window_set_default_size')));
        expect(
          LinuxMyApplicationEditor.ownedContent(
            patched.replaceFirst('gboolean', '// mine\n  gboolean'),
          ),
          owned,
        );
      }

      expect(LinuxMyApplicationEditor.ownedContent(_pristine), '');
    });
  });
}
