import 'dart:io';

import 'package:flutter_flavorizr/src/engine/processors/linux/linux_my_application_editor.dart';
import 'package:flutter_flavorizr/src/exception/malformed_resource_exception.dart';
import 'package:flutter_flavorizr/src/exception/unsafe_title_setter_exception.dart';
import 'package:test/test.dart';

const _titles = {'apple': 'Apple App', 'banana': 'Banana App'};

String _read(String path) => File(path).readAsStringSync();

String _begin(String name) =>
    '// ----- BEGIN $name (autogenerated by flutter_flavorizr) -----';
String _end(String name) =>
    '// ----- END $name (autogenerated by flutter_flavorizr) -----';

/// What a `flutter create` run writes: the title is two string literals.
final _pristine = _read(
  'test_resources/linux/my_application_processor_test/my_application.cc',
);

/// What a 2.x run wrote, or a template that declares the title: a variable and
/// a region that overrides it.
final _withVariable = _read(
  'test_resources/linux/my_application_processor_test/my_application_expected.cc',
);

/// The title declared as a variable, with the two setters still literals: the
/// variable is not read by anything.
final _plain = _pristine.replaceFirst(
  '  if (use_header_bar) {\n',
  '  const gchar* window_title = "example";\n  if (use_header_bar) {\n',
);

/// The declaration and the two setters that read it, which is what 2.x made of
/// a `flutter create` file.
final _readingTheVariable = _plain
    .replaceFirst(
      'gtk_header_bar_set_title(header_bar, "example");',
      'gtk_header_bar_set_title(header_bar, window_title);',
    )
    .replaceFirst(
      'gtk_window_set_title(window, "example");',
      'gtk_window_set_title(window, window_title);',
    );

/// The lines of [text] that are not inside a region.
List<String> _outsideTheRegions(String text) {
  final lines = <String>[];
  var inside = false;

  for (final line in text.split('\n')) {
    if (line.contains('BEGIN ')) inside = true;
    if (!inside) lines.add(line);
    if (line.contains('END ')) inside = false;
  }

  return lines;
}

void main() {
  group('LinuxMyApplicationEditor on a `flutter create` file', () {
    final patched = LinuxMyApplicationEditor.withWindowTitles(
      _pristine,
      _titles,
    );

    test('adds regions and changes nothing outside them', () {
      expect(_outsideTheRegions(patched), _outsideTheRegions(_pristine));
      expect(patched, isNot(contains('const gchar* window_title')));
    });

    test('overrides the title of the header bar and of the window, each '
        'right after the literal that sets it', () {
      expect(
        patched,
        contains(
          '    gtk_header_bar_set_title(header_bar, "example");\n'
          '    ${_begin('header_bar_title')}\n'
          '    #ifdef FLUTTER_APP_FLAVOR\n'
          '    if (g_strcmp0(FLUTTER_APP_FLAVOR, "apple") == 0) {\n'
          '      gtk_header_bar_set_title(header_bar, "Apple App");\n'
          '    } else if (g_strcmp0(FLUTTER_APP_FLAVOR, "banana") == 0) {\n'
          '      gtk_header_bar_set_title(header_bar, "Banana App");\n'
          '    }\n'
          '    #endif\n'
          '    ${_end('header_bar_title')}\n',
        ),
      );
      expect(
        patched,
        contains(
          '    gtk_window_set_title(window, "example");\n'
          '    ${_begin('plain_window_title')}\n'
          '    #ifdef FLUTTER_APP_FLAVOR\n'
          '    if (g_strcmp0(FLUTTER_APP_FLAVOR, "apple") == 0) {\n'
          '      gtk_window_set_title(window, "Apple App");\n'
          '    } else if (g_strcmp0(FLUTTER_APP_FLAVOR, "banana") == 0) {\n'
          '      gtk_window_set_title(window, "Banana App");\n'
          '    }\n'
          '    #endif\n'
          '    ${_end('plain_window_title')}\n',
        ),
      );
    });

    test('is idempotent', () {
      expect(
        LinuxMyApplicationEditor.withWindowTitles(patched, _titles),
        patched,
      );
    });

    test('regenerates the regions without the flavor that was removed', () {
      final removed = LinuxMyApplicationEditor.withWindowTitles(patched, {
        'apple': 'Apple App',
      });

      expect(removed, isNot(contains('banana')));
      expect(removed, isNot(contains('Banana App')));
      expect(_outsideTheRegions(removed), _outsideTheRegions(_pristine));
      expect(
        LinuxMyApplicationEditor.withWindowTitles(
          LinuxMyApplicationEditor.withWindowTitles(_pristine, {
            'apple': 'Apple App',
          }),
          _titles,
        ),
        patched,
      );
    });

    test('escapes the titles', () {
      expect(
        LinuxMyApplicationEditor.withWindowTitles(_pristine, {
          'apple': 'The "App"',
        }),
        contains(r'"The \"App\""'),
      );
    });

    test('writes regions that are balanced when there is no flavor to '
        'override', () {
      final patched = LinuxMyApplicationEditor.withWindowTitles(_pristine, {});

      expect(
        patched,
        contains(
          '    #ifdef FLUTTER_APP_FLAVOR\n'
          '    #endif\n'
          '    ${_end('header_bar_title')}',
        ),
      );
      expect(_outsideTheRegions(patched), _outsideTheRegions(_pristine));
    });

    test('fails when the title is set by neither a variable nor a literal', () {
      expect(
        () => LinuxMyApplicationEditor.withWindowTitles(
          'int main() {}\n',
          _titles,
        ),
        throwsA(isA<MalformedResourceException>()),
      );
    });
  });

  group('LinuxMyApplicationEditor on a file with a title variable', () {
    test('adds the region right after the variable, as 2.x did', () {
      final source = _withVariable.replaceAll(
        RegExp(
          r'  // ----- BEGIN window_title.*?END window_title[^\n]*\n',
          dotAll: true,
        ),
        '',
      );

      expect(
        LinuxMyApplicationEditor.withWindowTitles(source, _titles),
        _withVariable,
      );
    });

    test('leaves a file flavorized by 2.x as it is', () {
      expect(
        LinuxMyApplicationEditor.withWindowTitles(_withVariable, _titles),
        _withVariable,
      );
    });

    test('regenerates the region in place when a flavor is removed', () {
      final removed = LinuxMyApplicationEditor.withWindowTitles(_withVariable, {
        'apple': 'Apple App',
      });

      expect(removed, isNot(contains('banana')));
      expect(_outsideTheRegions(removed), _outsideTheRegions(_withVariable));
    });

    test('swaps the regions of the literals for the one of the variable when '
        'the setters read the variable', () {
      final flavorized = LinuxMyApplicationEditor.withWindowTitles(
        _pristine,
        _titles,
      );
      // The user declares the variable and points both setters to it.
      final converted = flavorized
          .replaceFirst(
            '  if (use_header_bar) {\n',
            '  const gchar* window_title = "example";\n  if (use_header_bar) {\n',
          )
          .replaceFirst(
            'gtk_header_bar_set_title(header_bar, "example");',
            'gtk_header_bar_set_title(header_bar, window_title);',
          )
          .replaceFirst(
            'gtk_window_set_title(window, "example");',
            'gtk_window_set_title(window, window_title);',
          );

      final patched = LinuxMyApplicationEditor.withWindowTitles(
        converted,
        _titles,
      );

      expect(patched, isNot(contains('header_bar_title')));
      expect(patched, isNot(contains('plain_window_title')));
      expect(
        patched,
        contains(
          '  const gchar* window_title = "example";\n'
          '  ${_begin('window_title')}\n',
        ),
      );
    });

    test('adds the region right after a declaration whose setters read it', () {
      final patched = LinuxMyApplicationEditor.withWindowTitles(
        _readingTheVariable,
        _titles,
      );

      expect(
        _outsideTheRegions(patched),
        _outsideTheRegions(_readingTheVariable),
      );
      expect(patched, contains(_begin('window_title')));
    });

    test('keeps the overrides of the setters that are still literals, since a '
        'variable cannot change a literal', () {
      // Declared, but nothing reads it.
      final patched = LinuxMyApplicationEditor.withWindowTitles(
        _plain,
        _titles,
      );

      expect(_outsideTheRegions(patched), _outsideTheRegions(_plain));
      expect(patched, contains(_begin('header_bar_title')));
      expect(patched, contains(_begin('plain_window_title')));
      expect(patched, isNot(contains(_begin('window_title'))));
      expect(
        LinuxMyApplicationEditor.withWindowTitles(patched, _titles),
        patched,
      );
    });

    test('overrides each setter in the way it sets the title when only one '
        'reads the variable', () {
      final mixed = _readingTheVariable.replaceFirst(
        'gtk_window_set_title(window, window_title);',
        'gtk_window_set_title(window, "example");',
      );

      final patched = LinuxMyApplicationEditor.withWindowTitles(mixed, _titles);

      expect(_outsideTheRegions(patched), _outsideTheRegions(mixed));
      expect(patched, contains(_begin('window_title')));
      expect(patched, contains(_begin('plain_window_title')));
      expect(patched, isNot(contains(_begin('header_bar_title'))));
    });

    test('drops the region of the variable that nothing reads anymore', () {
      final withRegion = LinuxMyApplicationEditor.withWindowTitles(
        _readingTheVariable,
        _titles,
      );
      final literals = withRegion
          .replaceFirst(
            'gtk_header_bar_set_title(header_bar, window_title);',
            'gtk_header_bar_set_title(header_bar, "example");',
          )
          .replaceFirst(
            'gtk_window_set_title(window, window_title);',
            'gtk_window_set_title(window, "example");',
          );

      final patched = LinuxMyApplicationEditor.withWindowTitles(
        literals,
        _titles,
      );

      expect(patched, isNot(contains(_begin('window_title'))));
      expect(patched, contains(_begin('header_bar_title')));
      expect(patched, contains(_begin('plain_window_title')));
    });
  });

  group('LinuxMyApplicationEditor with a setter the user changed', () {
    final flavorized = LinuxMyApplicationEditor.withWindowTitles(
      _pristine,
      _titles,
    );

    test('drops the region of a header bar setter that is not a literal '
        'anymore, so a removed flavor leaves no branch behind', () {
      final custom = flavorized.replaceFirst(
        'gtk_header_bar_set_title(header_bar, "example");',
        'gtk_header_bar_set_title(header_bar, custom_title);',
      );

      final patched = LinuxMyApplicationEditor.withWindowTitles(custom, {
        'apple': 'Apple App',
      });

      expect(patched, isNot(contains('header_bar_title')));
      expect(patched, contains(_begin('plain_window_title')));
      expect(patched, isNot(contains('Banana')));
      expect(_outsideTheRegions(patched), _outsideTheRegions(custom));
    });

    test(
      'drops the region of a window setter that is not a literal anymore',
      () {
        final custom = flavorized.replaceFirst(
          'gtk_window_set_title(window, "example");',
          'gtk_window_set_title(window, custom_title);',
        );

        final patched = LinuxMyApplicationEditor.withWindowTitles(custom, {
          'apple': 'Apple App',
        });

        expect(patched, isNot(contains('plain_window_title')));
        expect(patched, contains(_begin('header_bar_title')));
        expect(patched, isNot(contains('Banana')));
      },
    );

    test('fails once no setter is left to override, instead of keeping stale '
        'regions silently', () {
      final custom = flavorized
          .replaceFirst(
            'gtk_header_bar_set_title(header_bar, "example");',
            'gtk_header_bar_set_title(header_bar, custom_title);',
          )
          .replaceFirst(
            'gtk_window_set_title(window, "example");',
            'gtk_window_set_title(window, custom_title);',
          );

      expect(
        () => LinuxMyApplicationEditor.withWindowTitles(custom, _titles),
        throwsA(isA<MalformedResourceException>()),
      );
    });
  });

  group('LinuxMyApplicationEditor with comments of the user', () {
    String commented(String source) => source
        .replaceFirst(
          'gtk_header_bar_set_title(header_bar, "example");',
          'gtk_header_bar_set_title(header_bar, "example"); // Base title',
        )
        .replaceFirst(
          'gtk_window_set_title(window, "example");',
          'gtk_window_set_title(window, "example"); /* base */',
        );

    test('a comment after an already flavorized setter keeps its region, and '
        'a second run changes nothing', () {
      final flavorized = LinuxMyApplicationEditor.withWindowTitles(
        _pristine,
        _titles,
      );
      final edited = commented(flavorized);

      final once = LinuxMyApplicationEditor.withWindowTitles(edited, _titles);
      final twice = LinuxMyApplicationEditor.withWindowTitles(once, _titles);

      expect(once, edited);
      expect(twice, edited);
      expect(edited, contains(_begin('header_bar_title')));
      expect(edited, contains(_begin('plain_window_title')));
    });

    test('a comment after a setter does not stop a flavor from being '
        'removed from its region', () {
      final edited = commented(
        LinuxMyApplicationEditor.withWindowTitles(_pristine, _titles),
      );

      final removed = LinuxMyApplicationEditor.withWindowTitles(edited, {
        'apple': 'Apple App',
      });

      expect(removed, contains(_begin('header_bar_title')));
      expect(removed, isNot(contains('Banana')));
      expect(_outsideTheRegions(removed), _outsideTheRegions(edited));
    });

    test('a comment after a setter that was never flavorized gets its region '
        'right after it, and the line is left as it was', () {
      final edited = commented(_pristine);

      final patched = LinuxMyApplicationEditor.withWindowTitles(
        edited,
        _titles,
      );

      expect(_outsideTheRegions(patched), _outsideTheRegions(edited));
      expect(patched, contains(_begin('header_bar_title')));
      expect(patched, contains(_begin('plain_window_title')));
    });

    test(
      'a comment after the declaration keeps the region of the variable',
      () {
        final edited = _readingTheVariable.replaceFirst(
          'const gchar* window_title = "example";',
          'const gchar* window_title = "example"; // Base title',
        );
        final flavorized = LinuxMyApplicationEditor.withWindowTitles(
          edited,
          _titles,
        );

        expect(flavorized, contains(_begin('window_title')));
        expect(
          LinuxMyApplicationEditor.withWindowTitles(flavorized, _titles),
          flavorized,
        );
      },
    );
  });

  group('LinuxMyApplicationEditor with a declared title nothing reads', () {
    test('fails instead of writing assignments nobody reads', () {
      final unread = _readingTheVariable
          .replaceFirst(
            'gtk_header_bar_set_title(header_bar, window_title);',
            'gtk_header_bar_set_title(header_bar, custom_title);',
          )
          .replaceFirst(
            'gtk_window_set_title(window, window_title);',
            'gtk_window_set_title(window, custom_title);',
          );

      expect(
        () => LinuxMyApplicationEditor.withWindowTitles(unread, _titles),
        throwsA(isA<MalformedResourceException>()),
      );
    });

    test('still finds a reader that is not written like 2.x wrote it', () {
      final spread = _readingTheVariable
          .replaceFirst(
            'gtk_header_bar_set_title(header_bar, window_title);',
            'gtk_header_bar_set_title(\n        header_bar, window_title);',
          )
          .replaceFirst(
            'gtk_window_set_title(window, window_title);',
            'gtk_window_set_title(window,  window_title );',
          );

      final patched = LinuxMyApplicationEditor.withWindowTitles(
        spread,
        _titles,
      );

      expect(patched, contains(_begin('window_title')));
      expect(_outsideTheRegions(patched), _outsideTheRegions(spread));
    });

    test('a mention that is only a comment is no reader', () {
      final unread = _plain.replaceFirst(
        '  if (use_header_bar) {\n',
        '  // window_title is not used yet\n  if (use_header_bar) {\n',
      );

      final patched = LinuxMyApplicationEditor.withWindowTitles(
        unread,
        _titles,
      );

      expect(patched, isNot(contains(_begin('window_title'))));
      expect(patched, contains(_begin('header_bar_title')));
    });
  });

  group('LinuxMyApplicationEditor reading the variable past comments and '
      'strings', () {
    // The declaration is there, and both setters were changed to something
    // else: whatever mentions `window_title` below is the only thing left.
    final unread = _readingTheVariable
        .replaceFirst(
          'gtk_header_bar_set_title(header_bar, window_title);',
          'gtk_header_bar_set_title(header_bar, custom_title);',
        )
        .replaceFirst(
          'gtk_window_set_title(window, window_title);',
          'gtk_window_set_title(window, custom_title);',
        );

    void expectUnread(String source) => expect(
      () => LinuxMyApplicationEditor.withWindowTitles(source, _titles),
      throwsA(isA<MalformedResourceException>()),
    );

    test('a block comment on a line of its own is no reader', () {
      expectUnread(
        unread.replaceFirst(
          '  if (use_header_bar) {\n',
          '  /* window_title was previously used here */\n'
              '  if (use_header_bar) {\n',
        ),
      );
    });

    test(
      'a block comment before a statement on the same line is no reader',
      () {
        expectUnread(
          unread.replaceFirst(
            '  if (use_header_bar) {\n',
            '  /* window_title */ if (use_header_bar) {\n',
          ),
        );
      },
    );

    test('a comment after a custom setter is no reader', () {
      expectUnread(
        unread
            .replaceFirst(
              'gtk_header_bar_set_title(header_bar, custom_title);',
              'gtk_header_bar_set_title(header_bar, custom_title); '
                  '// window_title',
            )
            .replaceFirst(
              'gtk_window_set_title(window, custom_title);',
              'gtk_window_set_title(window, custom_title); /* window_title */',
            ),
      );
    });

    test('a block comment over several lines is no reader', () {
      expectUnread(
        unread.replaceFirst(
          '  if (use_header_bar) {\n',
          '  /*\n'
              '   * The title used to be window_title,\n'
              '   * which the setters read.\n'
              '   */\n'
              '  if (use_header_bar) {\n',
        ),
      );
    });

    test('a mention inside a string literal is no reader', () {
      expectUnread(
        unread.replaceFirst(
          '  if (use_header_bar) {\n',
          '  g_message("window_title");\n  if (use_header_bar) {\n',
        ),
      );
    });

    test('a real reader is still found after what looks like a comment in a '
        'string', () {
      final source = _readingTheVariable.replaceFirst(
        '  if (use_header_bar) {\n',
        '  const char* note = "/* not a comment // either";\n'
            '  if (use_header_bar) {\n',
      );

      final patched = LinuxMyApplicationEditor.withWindowTitles(
        source,
        _titles,
      );

      expect(patched, contains(_begin('window_title')));
      expect(_outsideTheRegions(patched), _outsideTheRegions(source));
    });

    test('a real reader on the line of a comment is found', () {
      final source = _readingTheVariable.replaceFirst(
        'gtk_window_set_title(window, window_title);',
        '/* title */ gtk_window_set_title(window, window_title); // reads it',
      );

      expect(
        LinuxMyApplicationEditor.withWindowTitles(source, _titles),
        contains(_begin('window_title')),
      );
    });
  });

  group('LinuxMyApplicationEditor with a setter that is not under a brace', () {
    const header = '    gtk_header_bar_set_title(header_bar, "example");\n';
    const window = '    gtk_window_set_title(window, "example");\n';

    void expectUnsafe(String source) => expect(
      () => LinuxMyApplicationEditor.withWindowTitles(source, _titles),
      throwsA(isA<UnsafeTitleSetterException>()),
    );

    test('rejects a setter that an unbraced `if` controls, since the region '
        'would run whatever the condition says', () {
      expectUnsafe(
        _pristine.replaceFirst(header, '    if (enabled)\n  $header'),
      );
    });

    test('rejects an unbraced `else`, `for` and `while`', () {
      for (final control in ['else', 'for (;;)', 'while (x)', '} else']) {
        expectUnsafe(_pristine.replaceFirst(window, '    $control\n  $window'));
      }
    });

    test('rejects a condition over several lines, past a comment', () {
      expectUnsafe(
        _pristine.replaceFirst(
          header,
          '    if (a &&\n        b)\n    // the title\n  $header',
        ),
      );
    });

    test('tells the user to add braces, and where', () {
      expect(
        () => LinuxMyApplicationEditor.withWindowTitles(
          _pristine.replaceFirst(header, '    if (enabled)\n  $header'),
          _titles,
        ),
        throwsA(
          isA<UnsafeTitleSetterException>().having(
            (error) => error.toString(),
            'message',
            allOf(contains('braces'), contains('gtk_header_bar_set_title')),
          ),
        ),
      );
    });

    test('keeps a braced `if`, a preprocessor condition and comments about '
        'control flow', () {
      for (final before in [
        '    if (enabled) {\n',
        '    #if defined(X)\n',
        '    // if (enabled)\n',
        '    /* else */\n',
      ]) {
        final source = _pristine.replaceFirst(header, '$before$header');

        expect(
          LinuxMyApplicationEditor.withWindowTitles(source, _titles),
          contains(_begin('header_bar_title')),
          reason: before,
        );
      }
    });
  });

  group('LinuxMyApplicationEditor with a setter that is commented out', () {
    const window = '    gtk_window_set_title(window, "example");\n';

    test('anchors on the active setter, not on one in a block comment before '
        'it', () {
      final source = _pristine.replaceFirst(
        window,
        '    /* gtk_window_set_title(window, "old"); */\n$window',
      );

      final patched = LinuxMyApplicationEditor.withWindowTitles(
        source,
        _titles,
      );

      expect(patched, contains('$window    ${_begin('plain_window_title')}\n'));
      expect(_outsideTheRegions(patched), _outsideTheRegions(source));
    });

    test('anchors on the active setter, not on one in a line comment or in a '
        'multi-line block comment before it', () {
      for (final comment in [
        '    // gtk_window_set_title(window, "old");\n',
        '    /*\n    gtk_window_set_title(window, "old");\n    */\n',
      ]) {
        final source = _pristine.replaceFirst(window, '$comment$window');

        final patched = LinuxMyApplicationEditor.withWindowTitles(
          source,
          _titles,
        );

        expect(
          patched,
          contains('$window    ${_begin('plain_window_title')}\n'),
          reason: comment,
        );
        expect(
          LinuxMyApplicationEditor.withWindowTitles(patched, _titles),
          patched,
        );
      }
    });

    test('a setter that only exists in a comment gets no region', () {
      final source = _pristine.replaceFirst(
        window,
        '    /* gtk_window_set_title(window, "old"); */\n',
      );

      final patched = LinuxMyApplicationEditor.withWindowTitles(
        source,
        _titles,
      );

      expect(patched, contains(_begin('header_bar_title')));
      expect(patched, isNot(contains(_begin('plain_window_title'))));
    });

    test('a setter after a comment on its own line is still found', () {
      final source = _pristine.replaceFirst(
        window,
        '    /* base */ gtk_window_set_title(window, "example");\n',
      );

      expect(
        LinuxMyApplicationEditor.withWindowTitles(source, _titles),
        contains(_begin('plain_window_title')),
      );
    });
  });

  group(
    'LinuxMyApplicationEditor with a title that has escaped characters',
    () {
      const escaped = r'The \"App\" \\';

      test('overrides literal setters', () {
        final source = _pristine.replaceAll('"example"', '"$escaped"');

        final patched = LinuxMyApplicationEditor.withWindowTitles(
          source,
          _titles,
        );

        expect(_outsideTheRegions(patched), _outsideTheRegions(source));
        expect(patched, contains(_begin('header_bar_title')));
        expect(patched, contains(_begin('plain_window_title')));
        expect(
          LinuxMyApplicationEditor.withWindowTitles(patched, _titles),
          patched,
        );
      });

      test('overrides a declaration', () {
        final source = _readingTheVariable.replaceFirst(
          'const gchar* window_title = "example";',
          'const gchar* window_title = "$escaped";',
        );

        final patched = LinuxMyApplicationEditor.withWindowTitles(
          source,
          _titles,
        );

        expect(_outsideTheRegions(patched), _outsideTheRegions(source));
        expect(patched, contains(_begin('window_title')));
      });
    },
  );

  group('LinuxMyApplicationEditor.ownedContent', () {
    test('is the regions and nothing else, whatever the mode', () {
      for (final source in [_pristine, _withVariable]) {
        final patched = LinuxMyApplicationEditor.withWindowTitles(
          source,
          _titles,
        );
        final owned = LinuxMyApplicationEditor.ownedContent(patched);

        expect(owned, contains('Apple App'));
        expect(owned, isNot(contains('gtk_window_set_default_size')));
        expect(
          LinuxMyApplicationEditor.ownedContent(
            patched.replaceFirst('gboolean', '// mine\n  gboolean'),
          ),
          owned,
        );
      }

      expect(LinuxMyApplicationEditor.ownedContent(_pristine), '');
    });
  });
