/// A logger that keeps what it is asked to print, whatever the level.
class _RecordingLogger extends Logger {
  final List<String> lines = [];
  final List<String> errors = [];

  _RecordingLogger() : super(level: Level.quiet);

  @override
  void info(String? message, {LogStyle? style}) => lines.add('$message');

  @override
  void err(String? message, {LogStyle? style}) {
    lines.add('$message');
    errors.add('$message');
  }

  @override
  void warn(String? message, {String tag = 'WARN', LogStyle? style}) =>
      lines.add('$message');

  @override
  void success(String? message, {LogStyle? style}) => lines.add('$message');
}

/// A resource that records what happens to it in [events].
class _FakeResource extends Resource<String> {
  @override
  final ResourceKey<String> key;

  final List<String> events;
  final Object? setupError;
  final Object? teardownError;

  /// The `success` flag of each teardown call.
  final List<bool> teardownSuccess = [];

  _FakeResource(String name, this.events, {this.setupError, this.teardownError})
    : key = ResourceKey<String>(name);

  String get name => key.name;

  @override
  Future<String> setup(FlavorizrContext ctx) async {
    events.add('setup $name');
    if (setupError != null) {
      throw setupError!;
    }

    return 'value of $name';
  }

  @override
  Future<void> teardown(
    FlavorizrContext ctx,
    String value, {
    required bool success,
  }) async {
    events.add('teardown $name');
    teardownSuccess.add(success);
    if (teardownError != null) {
      throw teardownError!;
    }
  }
}

/// A processor that writes `lib/<id>.dart` in the shadow workspace, and fails
/// with [error] once it did, like a processor hitting a malformed project.
class _FakeProcessor extends FlavorizrProcessor {
  @override
  final String id;

  final List<String> events;
  final List<_FakeResource> needs;
  final Object? error;

  _FakeProcessor(this.id, this.events, {this.needs = const [], this.error});

  @override
  Set<ResourceKey<Object?>> get requires => {
    for (final resource in needs) resource.key,
  };

  @override
  Future<void> apply(FlavorizrContext ctx) async {
    events.add('apply $id');
    File(ctx.resolve('lib/$id.dart')).writeAsStringSync('generated by $id');
    ctx.track(Artifact.managed('lib/$id.dart'));
    if (error != null) {
      throw error!;
    }
  }
}

void main() {
  late ShadowFixture fx;
  late List<String> events;
  late _RecordingLogger logger;

  setUp(() {
    fx = ShadowFixture();
    events = [];
    logger = _RecordingLogger();
    fx.project.write('lib/main.dart', 'main');
  });
  tearDown(() => fx.dispose());

  ExecutionPlan planOf(List<_FakeProcessor> processors) => resolveExecutionPlan(
    processors,
    requested: processors.map((processor) => processor.id),
  );

  /// Executes [processors] against the fixture project, in id order.
  Future<ExecutionReport> execute(
    List<_FakeProcessor> processors, {
    List<_FakeResource> resources = const [],
    Future<void> Function(ShadowWorkspace shadow, FlavorizrContext ctx)?
    commit,
    Directory? tempParent,
  }) => PlanExecutor(logger: logger).execute(
    planOf(processors),
    config: TestUtils.parseFlavorizr('test_resources/pubspec'),
    projectRoot: fx.project.root,
    paths: ['lib'],
    resources: resources,
    tempParent: tempParent,
    commit:
        commit ??
        (shadow, ctx) async {
          events.add('commit');
        },
  );

  group('PlanExecutor', () {
    test('applies the plan in order and commits what it wrote', () async {
      final tracked = <String>[];

      final report = await execute(
        [_FakeProcessor('b', events), _FakeProcessor('a', events)],
        commit: (shadow, ctx) async {
          events.add('commit');
          tracked.addAll(ctx.tracked.map((artifact) => artifact.path));
          expect(shadow.read('lib/a.dart'), 'generated by a');
        },
      );

      expect(events, ['apply a', 'apply b', 'commit']);
      expect(tracked, ['lib/a.dart', 'lib/b.dart']);
      expect(report.succeeded, isTrue);
      expect(report.completed, ['a', 'b']);
      expect(report.failed, isNull);
      expect(report.skipped, isEmpty);
      expect(report.exitCode, 0);
    });

    group('when a processor throws', () {
      late Directory tempParent;
      late ExecutionReport report;
      final error = StateError('malformed project');

      setUp(() async {
        tempParent = Directory(p.join(fx.scratch.path, 'tmp'))..createSync();
        fx.project.write('lib/a.dart', 'hand written');

        report = await execute(
          [
            _FakeProcessor('a', events),
            _FakeProcessor('b', events, error: error),
            _FakeProcessor('c', events),
          ],
          tempParent: tempParent,
        );
      });

      test('stops there and reports what ran, failed and was skipped', () {
        expect(events, ['apply a', 'apply b']);
        expect(report.succeeded, isFalse);
        expect(report.completed, ['a']);
        expect(report.failed, 'b');
        expect(report.skipped, ['c']);
        expect(report.error, same(error));
        expect(report.stackTrace, isNotNull);
        expect(report.exitCode, isNot(0));
      });

      test('never commits', () {
        expect(events, isNot(contains('commit')));
      });

      test('leaves the real project untouched', () {
        expect(fx.project.read('lib/a.dart'), 'hand written');
        expect(fx.project.read('lib/main.dart'), 'main');
        expect(fx.project.exists('lib/b.dart'), isFalse);
        expect(fx.project.exists(LockStore.fileName), isFalse);
      });

      test('deletes the shadow workspace', () {
        expect(tempParent.listSync(), isEmpty);
      });
    });

    group('with a commit that copies back and writes the lock', () {
      Future<void> persist(ShadowWorkspace shadow, FlavorizrContext ctx) async {
        await shadow.copyBack(await shadow.diff(tracked: ctx.tracked));
        await LockStore(
          fx.project.root,
          runningVersion: '3.0.0',
        ).write(FlavorizrLock(flavorizrVersion: '3.0.0'));
      }

      test('a run that went well writes the files and the lock', () async {
        await execute([
          _FakeProcessor('a', events),
          _FakeProcessor('b', events),
        ], commit: persist);

        expect(fx.project.read('lib/a.dart'), 'generated by a');
        expect(fx.project.read('lib/b.dart'), 'generated by b');
        expect(fx.project.exists(LockStore.fileName), isTrue);
      });

      test('a failing run writes neither a file nor the lock', () async {
        fx.project.write('lib/a.dart', 'hand written');
        final lock = FlavorizrLock(
          flavorizrVersion: '2.9.0',
          flavors: {'apple': 'hash'},
        );
        await LockStore(
          fx.project.root,
          runningVersion: '3.0.0',
        ).write(lock);
        final before = fx.project.read(LockStore.fileName);

        final report = await execute([
          _FakeProcessor('a', events),
          _FakeProcessor('b', events, error: StateError('boom')),
        ], commit: persist);

        expect(report.succeeded, isFalse);
        expect(fx.project.read('lib/a.dart'), 'hand written');
        expect(fx.project.exists('lib/b.dart'), isFalse);
        expect(fx.project.read(LockStore.fileName), before);
      });
    });

    group('when the commit throws', () {
      test('the error is not swallowed and the shadow is deleted', () async {
        final tempParent = Directory(p.join(fx.scratch.path, 'tmp'))
          ..createSync();
        final error = StateError('copy-back refused');

        await expectLater(
          execute(
            [_FakeProcessor('a', events)],
            tempParent: tempParent,
            commit: (shadow, ctx) async => throw error,
          ),
          throwsA(same(error)),
        );

        expect(tempParent.listSync(), isEmpty);
      });
    });

    group('the report', () {
      test('is printed as an error when the run failed', () async {
        await execute([
          _FakeProcessor('a', events),
          _FakeProcessor('b', events, error: StateError('malformed project')),
          _FakeProcessor('c', events),
        ]);

        expect(logger.lines, [
          'Completed: a\n'
              'Failed: b (Bad state: malformed project)\n'
              'Skipped: c',
        ]);
        expect(logger.errors, logger.lines);
      });

      test('is printed when a resource failed, not a processor', () async {
        final xcode = _FakeResource(
          'xcode',
          events,
          setupError: StateError('no xcode'),
        );

        await execute([
          _FakeProcessor('a', events, needs: [xcode]),
        ], resources: [xcode]);

        expect(logger.errors, [
          'Failed: Bad state: no xcode\n'
              'Skipped: a',
        ]);
      });

      test('is printed before the commit, when the run went well', () async {
        late List<String> printedBeforeCommit;

        await execute(
          [_FakeProcessor('a', events), _FakeProcessor('b', events)],
          commit: (shadow, ctx) async {
            printedBeforeCommit = [...logger.lines];
          },
        );

        expect(printedBeforeCommit, ['Completed: a, b']);
        expect(logger.errors, isEmpty);
      });
    });

    group('resources', () {
      test('are torn down, unsuccessfully, when a processor throws', () async {
        final xcode = _FakeResource('xcode', events);
        final pods = _FakeResource('pods', events);

        final report = await execute(
          [
            _FakeProcessor('a', events, needs: [xcode, pods]),
            _FakeProcessor('b', events, error: StateError('boom')),
            _FakeProcessor('c', events, needs: [xcode]),
          ],
          resources: [xcode, pods],
        );

        expect(events, [
          'setup pods',
          'setup xcode',
          'apply a',
          // `pods` is not needed anymore: it is released with the last user.
          'teardown pods',
          'apply b',
          'teardown xcode',
        ]);
        expect(pods.teardownSuccess, [true]);
        expect(xcode.teardownSuccess, [false]);
        expect(report.failed, 'b');
        expect(report.skipped, ['c']);
      });

      test('are torn down when the processor that uses them throws', () async {
        final xcode = _FakeResource('xcode', events);

        final report = await execute(
          [
            _FakeProcessor(
              'a',
              events,
              needs: [xcode],
              error: StateError('boom'),
            ),
          ],
          resources: [xcode],
        );

        expect(events, ['setup xcode', 'apply a', 'teardown xcode']);
        expect(xcode.teardownSuccess, [false]);
        expect(report.failed, 'a');
      });

      test('that fail to set up abort the run before any processor', () async {
        final error = StateError('no xcode');
        final xcode = _FakeResource('xcode', events, setupError: error);

        final report = await execute(
          [
            _FakeProcessor('a', events),
            _FakeProcessor('b', events, needs: [xcode]),
          ],
          resources: [xcode],
        );

        expect(events, ['apply a', 'setup xcode']);
        expect(report.succeeded, isFalse);
        expect(report.error, same(error));
        expect(report.completed, ['a']);
        expect(report.failed, isNull);
        expect(report.skipped, ['b']);
      });

      test('that fail to tear down fail a run that went well', () async {
        final error = StateError('xcode is stuck');
        final xcode = _FakeResource('xcode', events, teardownError: error);

        final report = await execute([
          _FakeProcessor('a', events, needs: [xcode]),
        ], resources: [xcode]);

        expect(report.succeeded, isFalse);
        expect(report.error, same(error));
        expect(report.completed, ['a']);
        expect(report.failed, isNull);
        expect(report.skipped, isEmpty);
        expect(events, isNot(contains('commit')));
        expect(report.exitCode, isNot(0));
      });
    });
  });
}
